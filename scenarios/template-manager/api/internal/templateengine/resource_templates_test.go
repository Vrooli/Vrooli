package templateengine

import (
	"context"
	"path/filepath"
	"testing"

	repocontract "github.com/vrooli/repo-contract-go"
)

func TestResourceTemplateGenerateDryRunUsesSharedRenderer(t *testing.T) {
	root, err := repocontract.FindRepoRootFromEnvOrCWD()
	if err != nil {
		t.Fatalf("repo root: %v", err)
	}
	engine, err := New(root)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	report, err := engine.GenerateResourceTemplate(context.Background(), ResourceTemplateGenerateRequest{
		TemplateName: "external-cli",
		Destination:  filepath.Join(t.TempDir(), "demo-tool"),
		DryRun:       true,
		Values: map[string]string{
			"RESOURCE_NAME":         "demo-tool",
			"RESOURCE_DISPLAY_NAME": "Demo Tool",
			"RESOURCE_DESCRIPTION":  "Dry-run resource generated by Template Manager tests.",
		},
	})
	if err != nil {
		t.Fatalf("GenerateResourceTemplate dry-run: %v", err)
	}
	if report.Template.Name != "external-cli" {
		t.Fatalf("template = %q, want external-cli", report.Template.Name)
	}
	if !report.DryRun {
		t.Fatal("DryRun = false, want true")
	}
	if got := report.Values["RESOURCE_TEMPLATE"]; got != "external-cli" {
		t.Fatalf("RESOURCE_TEMPLATE = %q, want external-cli", got)
	}
	if len(report.Files) == 0 {
		t.Fatal("expected dry-run file preview")
	}
}

func TestResourceTemplateValidateCatalog(t *testing.T) {
	root, err := repocontract.FindRepoRootFromEnvOrCWD()
	if err != nil {
		t.Fatalf("repo root: %v", err)
	}
	engine, err := New(root)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	items, err := engine.ListResourceTemplates(context.Background())
	if err != nil {
		t.Fatalf("ListResourceTemplates: %v", err)
	}
	if len(items) < len(canonicalResourceTemplateNames) {
		t.Fatalf("resource template count = %d, want at least %d", len(items), len(canonicalResourceTemplateNames))
	}
}
