#!/usr/bin/env node
/**
 * Generate `src/routes.generated.ts` from `flow/navigation.json`.
 *
 * Mirrors the shape that `scenarios/flow-verifier/ui/src/routes.generated.ts`
 * exposes — `ROUTES` (builders), `ROUTE_PATTERNS` (raw patterns), `ROUTE_IDS`,
 * `PUBLIC_ROUTES`, `AUTH_REQUIRED_ROUTES` — so feature code can import
 * `ROUTE_PATTERNS` and `<Route path={ROUTE_PATTERNS.foo} />` stays typed.
 *
 * Usage:
 *   node scripts/gen-routes.mjs            # writes the file
 *   node scripts/gen-routes.mjs --check    # exits non-zero if file is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_UI_DIR = resolve(__dirname, "..");
const NAV_PATH = resolve(REPO_UI_DIR, "flow/navigation.json");
const OUT_PATH = resolve(REPO_UI_DIR, "src/routes.generated.ts");

const CHECK_ONLY = process.argv.includes("--check");

const PARAM_PATTERN = /:([a-zA-Z_][a-zA-Z0-9_]*)/g;

function camelize(id) {
  return id
    .split(/[_\-]/)
    .map((part, idx) => (idx === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");
}

function extractParams(path) {
  const params = [];
  let match;
  PARAM_PATTERN.lastIndex = 0;
  while ((match = PARAM_PATTERN.exec(path)) !== null) {
    params.push(match[1]);
  }
  return params;
}

function buildBuilder(path, params) {
  if (params.length === 0) {
    return JSON.stringify(path);
  }
  const args = params.map((p) => `${p}: string`).join(", ");
  let body = path;
  for (const p of params) {
    body = body.replace(`:${p}`, `\${${p}}`);
  }
  return `(${args}): string => \`${body}\``;
}

function generate(nav) {
  const routes = [...nav.routes].sort((a, b) => a.id.localeCompare(b.id));

  const builderLines = routes.map((r) => {
    const key = camelize(r.id);
    const params = extractParams(r.path);
    return `  ${key}: ${buildBuilder(r.path, params)},`;
  });

  const patternLines = routes.map((r) => {
    const key = camelize(r.id);
    return `  ${key}: ${JSON.stringify(r.path)},`;
  });

  const ids = routes.map((r) => `"${camelize(r.id)}"`).join(", ");

  return `// Code generated by ui-health. DO NOT EDIT.
// Source: ../ui/flow/navigation.json
// FlowId: ${nav.flowId}

export const ROUTES = {
${builderLines.join("\n")}
} as const;

export const ROUTE_PATTERNS = {
${patternLines.join("\n")}
} as const;

export const PUBLIC_ROUTES: readonly (keyof typeof ROUTES)[] = [${ids}];

export const AUTH_REQUIRED_ROUTES: readonly (keyof typeof ROUTES)[] = [];

export const ROUTE_IDS: readonly (keyof typeof ROUTES)[] = [${ids}];
`;
}

function main() {
  if (!existsSync(NAV_PATH)) {
    console.error(`✗ navigation.json not found at ${NAV_PATH}`);
    process.exit(1);
  }
  const nav = JSON.parse(readFileSync(NAV_PATH, "utf8"));
  const next = generate(nav);

  if (CHECK_ONLY) {
    const current = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : "";
    if (current !== next) {
      console.error(
        "✗ src/routes.generated.ts is out of date. Run `pnpm routes:gen` and commit the result.",
      );
      process.exit(1);
    }
    console.log("✓ routes.generated.ts is up to date");
    return;
  }

  writeFileSync(OUT_PATH, next, "utf8");
  console.log(`✓ wrote ${OUT_PATH.replace(REPO_UI_DIR + "/", "")}`);
}

main();
