package providercatalog

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

const generatedHeader = "// Code generated by api/cmd/gen-catalog from api/internal/providercatalog/catalog.seed.json; DO NOT EDIT.\n" +
	"//\n" +
	"// Source : api/internal/providercatalog/catalog.seed.json\n" +
	"// Codegen: api/cmd/gen-catalog (invoked by `make catalog-gen`)\n" +
	"// Drift  : api/internal/providercatalog/render_test.go fails the build if this file is stale.\n"

// RenderCapabilitiesGo renders api/internal/capabilities/catalog.generated.go.
// It emits the load-bearing capabilities.Def catalogue plus helper tables that
// mirror the providercatalog accessors. The output is deterministic (seed
// order, with the feature table sorted) so the drift test can compare bytes.
func RenderCapabilitiesGo() (string, error) {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("\npackage capabilities\n\n")
	b.WriteString("import (\n")
	b.WriteString("\tcommonv1 \"github.com/vrooli/vrooli/packages/proto/gen/go/audio-tools/v1/common\"\n")
	b.WriteString("\tdiagv1 \"github.com/vrooli/vrooli/packages/proto/gen/go/audio-tools/v1/diagnostics\"\n")
	b.WriteString(")\n\n")

	r := Default()
	b.WriteString("// generatedKnown is the active provider catalogue in seed order.\n")
	b.WriteString("var generatedKnown = []Def{\n")
	for _, p := range r.Active() {
		renderDef(&b, p)
	}
	b.WriteString("}\n\n")

	b.WriteString("// generatedFeatureCapabilities is the closed feature vocabulary. The\n")
	b.WriteString("// diagnostics proto has no speaker capability, so speaker evidence is folded\n")
	b.WriteString("// into CAPABILITY_STT for compatibility with the existing health rollup.\n")
	b.WriteString("var generatedFeatureCapabilities = map[string]diagv1.Capability{\n")
	for _, feature := range KnownFeatures() {
		capability, _ := r.CapabilityForFeature(feature)
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(feature), protoCapabilityConstant(capability))
	}
	b.WriteString("}\n\n")
	b.WriteString("func generatedCapabilityForFeature(feature string) (diagv1.Capability, bool) {\n")
	b.WriteString("\tcapability, ok := generatedFeatureCapabilities[feature]\n")
	b.WriteString("\treturn capability, ok\n")
	b.WriteString("}\n\n")

	b.WriteString("// generatedProviderTiers maps every declared provider ID to its routing tier.\n")
	b.WriteString("var generatedProviderTiers = map[string]commonv1.ProviderTier{\n")
	for _, p := range r.All() {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(p.ID), protoTierConstant(p.Tier))
	}
	b.WriteString("}\n\n")
	b.WriteString("func generatedTierForProviderID(id string) commonv1.ProviderTier {\n")
	b.WriteString("\ttier, ok := generatedProviderTiers[id]\n")
	b.WriteString("\tif !ok {\n")
	b.WriteString("\t\treturn commonv1.ProviderTier_PROVIDER_TIER_UNSPECIFIED\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn tier\n")
	b.WriteString("}\n\n")

	b.WriteString("// generatedResourceSlugs lists the active local-resource providers lifecycle\n")
	b.WriteString("// actions may target, keyed by stable provider ID.\n")
	b.WriteString("var generatedResourceSlugs = map[string]string{\n")
	for _, p := range r.Active() {
		if slug, ok := r.ResourceSlugForProviderID(p.ID); ok {
			fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(p.ID), strconv.Quote(slug))
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("func generatedResourceSlugForProviderID(id string) (string, bool) {\n")
	b.WriteString("\tslug, ok := generatedResourceSlugs[id]\n")
	b.WriteString("\treturn slug, ok\n")
	b.WriteString("}\n\n")
	b.WriteString("func generatedIsLocalProvider(id string) bool {\n")
	b.WriteString("\t_, ok := generatedResourceSlugs[id]\n")
	b.WriteString("\treturn ok\n")
	b.WriteString("}\n\n")

	b.WriteString("// generatedPullModelProviders is the set of providers that advertise pull_model.\n")
	b.WriteString("var generatedPullModelProviders = map[string]struct{}{\n")
	for _, p := range r.Active() {
		if r.SupportsPullModel(p.ID) {
			fmt.Fprintf(&b, "\t%s: {},\n", strconv.Quote(p.ID))
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("func generatedSupportsPullModel(id string) bool {\n")
	b.WriteString("\t_, ok := generatedPullModelProviders[id]\n")
	b.WriteString("\treturn ok\n")
	b.WriteString("}\n\n")

	b.WriteString("// generatedProviderActions lists the lifecycle verbs advertised by each active\n")
	b.WriteString("// local-resource provider.\n")
	b.WriteString("var generatedProviderActions = map[string][]string{\n")
	for _, p := range r.Active() {
		actions := r.ActionsForProvider(p.ID)
		if len(actions) == 0 {
			continue
		}
		quoted := make([]string, 0, len(actions))
		for _, action := range actions {
			quoted = append(quoted, strconv.Quote(string(action)))
		}
		fmt.Fprintf(&b, "\t%s: {%s},\n", strconv.Quote(p.ID), strings.Join(quoted, ", "))
	}
	b.WriteString("}\n\n")
	b.WriteString("func generatedActionsForProvider(id string) []string {\n")
	b.WriteString("\tactions, ok := generatedProviderActions[id]\n")
	b.WriteString("\tif !ok {\n")
	b.WriteString("\t\treturn nil\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn append([]string(nil), actions...)\n")
	b.WriteString("}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("format generated Go catalogue: %w", err)
	}
	return string(formatted), nil
}

func renderDef(b *strings.Builder, p Provider) {
	b.WriteString("\t{\n")
	fmt.Fprintf(b, "\t\tID: %s,\n", strconv.Quote(p.ID))
	fmt.Fprintf(b, "\t\tName: %s,\n", strconv.Quote(p.Name))
	fmt.Fprintf(b, "\t\tDescription: %s,\n", strconv.Quote(p.Description))
	fmt.Fprintf(b, "\t\tDependencyKind: %s,\n", dependencyKindConstant(p.DependencyKind))
	fmt.Fprintf(b, "\t\tDependencySlug: %s,\n", strconv.Quote(p.DependencySlug))
	fmt.Fprintf(b, "\t\tFeatures: []string{%s},\n", quoteList(p.Features))
	if p.Platform.Support != "" {
		if p.Platform.Reason != "" {
			fmt.Fprintf(b, "\t\tPlatform: PlatformVerdict{Support: %s, Reason: %s},\n", platformConstant(p.Platform.Support), strconv.Quote(p.Platform.Reason))
		} else {
			fmt.Fprintf(b, "\t\tPlatform: PlatformVerdict{Support: %s},\n", platformConstant(p.Platform.Support))
		}
	}
	fmt.Fprintf(b, "\t\tCriticality: %s,\n", criticalityConstant(p.Criticality))
	fmt.Fprintf(b, "\t\tActionKind: %s,\n", defActionKindConstant(p.DefActionKind))
	if p.OperatorCommand != "" {
		fmt.Fprintf(b, "\t\tOperatorCommand: %s,\n", strconv.Quote(p.OperatorCommand))
	}
	b.WriteString("\t},\n")
}

func quoteList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, strconv.Quote(value))
	}
	return strings.Join(quoted, ", ")
}

func dependencyKindConstant(kind DependencyKind) string {
	switch kind {
	case DependencyResource:
		return "DependencyResource"
	default:
		return "DependencyScenario"
	}
}

func criticalityConstant(criticality Criticality) string {
	if criticality == CriticalityRequired {
		return "CriticalityRequired"
	}
	return "CriticalityOptional"
}

func defActionKindConstant(kind DefActionKind) string {
	switch kind {
	case DefActionOperatorCommand:
		return "ActionKindOperatorCommand"
	case DefActionScenarioStart:
		return "ActionKindScenarioStart"
	case DefActionScenarioRestart:
		return "ActionKindScenarioRestart"
	case DefActionOwnerGuidance:
		return "ActionKindOwnerGuidance"
	default:
		return "ActionKindNone"
	}
}

func platformConstant(support PlatformSupport) string {
	switch support {
	case PlatformDegraded:
		return "PlatformDegraded"
	case PlatformUnsupported:
		return "PlatformUnsupported"
	default:
		return "PlatformSupported"
	}
}

func protoCapabilityConstant(capability Capability) string {
	switch capability {
	case CapabilityTTS:
		return "diagv1.Capability_CAPABILITY_TTS"
	case CapabilitySummarize:
		return "diagv1.Capability_CAPABILITY_SUMMARIZE"
	case CapabilityTranscode:
		return "diagv1.Capability_CAPABILITY_TRANSCODE"
	case CapabilitySpeaker:
		// The diagnostics proto has no speaker capability; health folds speaker
		// providers into the STT rollup.
		return "diagv1.Capability_CAPABILITY_STT"
	default:
		return "diagv1.Capability_CAPABILITY_STT"
	}
}

func protoTierConstant(tier Tier) string {
	switch tier {
	case TierLocal:
		return "commonv1.ProviderTier_PROVIDER_TIER_LOCAL"
	case TierBYOK:
		return "commonv1.ProviderTier_PROVIDER_TIER_BYOK"
	case TierVrooli:
		return "commonv1.ProviderTier_PROVIDER_TIER_VROOLI"
	case TierBrowser:
		return "commonv1.ProviderTier_PROVIDER_TIER_BROWSER"
	default:
		return "commonv1.ProviderTier_PROVIDER_TIER_UNSPECIFIED"
	}
}

// RenderTS renders ui/src/features/providers/providerCatalog.generated.ts. The
// UI consumes the provider metadata and TTS_ADAPTERS; no hand-maintained
// provider table remains in the page.
func RenderTS() (string, error) {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("//\n")
	b.WriteString("// Provider IDs are stable across health, lifecycle, settings, and usage.\n")
	b.WriteString("// Engine IDs are the STT stream-selection identifiers. TTS_ADAPTERS is the\n")
	b.WriteString("// matrix column vocabulary used by the Voices page.\n\n")

	b.WriteString("export type ProviderKind = \"scenario\" | \"local_resource\" | \"local_inprocess\" | \"byok_api\" | \"gateway\" | \"browser\";\n")
	b.WriteString("export type ProviderTier = \"local\" | \"byok\" | \"vrooli\" | \"browser\" | \"none\";\n")
	b.WriteString("export type ProviderStatus = \"active\" | \"planned\" | \"experimental\" | \"watch\";\n")
	b.WriteString("export type ProviderCapability = \"stt\" | \"tts\" | \"summarize\" | \"transcode\" | \"speaker\";\n")
	b.WriteString("export type ProviderCheckerKind = \"http_json\" | \"command\" | \"resource\" | \"none\";\n\n")

	b.WriteString("export interface ProviderMeta {\n")
	b.WriteString("  readonly id: string;\n")
	b.WriteString("  readonly name: string;\n")
	b.WriteString("  readonly description: string;\n")
	b.WriteString("  readonly kind: ProviderKind;\n")
	b.WriteString("  readonly tier: ProviderTier;\n")
	b.WriteString("  readonly status: ProviderStatus;\n")
	b.WriteString("  readonly capabilities: readonly ProviderCapability[];\n")
	b.WriteString("  readonly features: readonly string[];\n")
	b.WriteString("  readonly engineIds: readonly string[];\n")
	b.WriteString("  readonly resourceSlug: string;\n")
	b.WriteString("  readonly models: readonly string[];\n")
	b.WriteString("  readonly checkerKind: ProviderCheckerKind;\n")
	b.WriteString("  readonly platformSupport: \"supported\" | \"degraded\" | \"unsupported\";\n")
	b.WriteString("  readonly platformReason?: string;\n")
	b.WriteString("  readonly docsUrl?: string;\n")
	b.WriteString("  readonly operatorCommand?: string;\n")
	b.WriteString("  readonly adapterId?: string;\n")
	b.WriteString("  readonly license?: string;\n")
	b.WriteString("  readonly labelKey: string;\n")
	b.WriteString("  readonly descriptionKey: string;\n")
	b.WriteString("}\n\n")

	r := Default()
	b.WriteString("export const PROVIDERS: Readonly<Record<string, ProviderMeta>> = {\n")
	for _, p := range r.All() {
		renderTSProvider(&b, p)
	}
	b.WriteString("};\n\n")

	b.WriteString("export const ACTIVE_PROVIDER_IDS: readonly string[] = [\n")
	for _, p := range r.Active() {
		fmt.Fprintf(&b, "  %s,\n", strconv.Quote(p.ID))
	}
	b.WriteString("];\n\n")
	b.WriteString("export const ACTIVE_PROVIDERS: readonly ProviderMeta[] = ACTIVE_PROVIDER_IDS\n")
	b.WriteString("  .map((id) => PROVIDERS[id])\n")
	b.WriteString("  .filter((provider): provider is ProviderMeta => provider !== undefined);\n\n")

	b.WriteString("export const TTS_ADAPTERS: readonly string[] = [\n")
	for _, p := range r.ByCapability(CapabilityTTS) {
		if p.AdapterID == "" {
			continue
		}
		fmt.Fprintf(&b, "  %s,\n", strconv.Quote(p.AdapterID))
	}
	b.WriteString("];\n\n")

	b.WriteString("export const providerMeta = (id: string): ProviderMeta | undefined => PROVIDERS[id];\n")
	return b.String(), nil
}

func renderTSProvider(b *strings.Builder, p Provider) {
	fmt.Fprintf(b, "  %s: {\n", strconv.Quote(p.ID))
	fmt.Fprintf(b, "    id: %s,\n", strconv.Quote(p.ID))
	fmt.Fprintf(b, "    name: %s,\n", strconv.Quote(p.Name))
	fmt.Fprintf(b, "    description: %s,\n", strconv.Quote(p.Description))
	fmt.Fprintf(b, "    kind: %s,\n", strconv.Quote(string(p.Kind)))
	fmt.Fprintf(b, "    tier: %s,\n", strconv.Quote(string(p.Tier)))
	fmt.Fprintf(b, "    status: %s,\n", strconv.Quote(string(p.Status)))
	fmt.Fprintf(b, "    capabilities: [%s],\n", quoteList(capabilityStrings(p.Capabilities)))
	fmt.Fprintf(b, "    features: [%s],\n", quoteList(p.Features))
	fmt.Fprintf(b, "    engineIds: [%s],\n", quoteList(p.EngineIDs))
	fmt.Fprintf(b, "    resourceSlug: %s,\n", strconv.Quote(p.ResourceSlug))
	fmt.Fprintf(b, "    models: [%s],\n", quoteList(p.Models))
	fmt.Fprintf(b, "    checkerKind: %s,\n", strconv.Quote(string(p.CheckerKind)))
	fmt.Fprintf(b, "    platformSupport: %s,\n", strconv.Quote(string(p.Platform.Support)))
	if p.Platform.Reason != "" {
		fmt.Fprintf(b, "    platformReason: %s,\n", strconv.Quote(p.Platform.Reason))
	}
	if p.DocsURL != "" {
		fmt.Fprintf(b, "    docsUrl: %s,\n", strconv.Quote(p.DocsURL))
	}
	if p.OperatorCommand != "" {
		fmt.Fprintf(b, "    operatorCommand: %s,\n", strconv.Quote(p.OperatorCommand))
	}
	if p.AdapterID != "" {
		fmt.Fprintf(b, "    adapterId: %s,\n", strconv.Quote(p.AdapterID))
	}
	if p.License != "" {
		fmt.Fprintf(b, "    license: %s,\n", strconv.Quote(p.License))
	}
	fmt.Fprintf(b, "    labelKey: %s,\n", strconv.Quote(p.Presentation.LabelKey))
	fmt.Fprintf(b, "    descriptionKey: %s,\n", strconv.Quote(p.Presentation.DescriptionKey))
	b.WriteString("  },\n")
}

func capabilityStrings(capabilities []Capability) []string {
	out := make([]string, 0, len(capabilities))
	for _, capability := range capabilities {
		out = append(out, string(capability))
	}
	return out
}
