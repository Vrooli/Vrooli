package providercatalog_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"audio-tools/internal/providercatalog"
)

const staleHint = "run `make catalog-gen` from scenarios/audio-tools"

func TestGeneratedGoCatalogIsNotStale(t *testing.T) {
	want, err := providercatalog.RenderCapabilitiesGo()
	require.NoError(t, err)
	path := filepath.Join("..", "capabilities", "catalog.generated.go")
	got, err := os.ReadFile(path)
	require.NoError(t, err, "read %s; %s", path, staleHint)
	require.Equal(t, want, string(got), "%s is stale; %s", path, staleHint)
}

func TestGeneratedTSProviderCatalogIsNotStale(t *testing.T) {
	want, err := providercatalog.RenderTS()
	require.NoError(t, err)
	path := filepath.Join("..", "..", "..", "ui", "src", "features", "providers", "providerCatalog.generated.ts")
	got, err := os.ReadFile(path)
	require.NoError(t, err, "read %s; %s", path, staleHint)
	require.Equal(t, want, string(got), "%s is stale; %s", path, staleHint)
}

func TestRenderingIsDeterministic(t *testing.T) {
	firstGo, err := providercatalog.RenderCapabilitiesGo()
	require.NoError(t, err)
	secondGo, err := providercatalog.RenderCapabilitiesGo()
	require.NoError(t, err)
	require.Equal(t, firstGo, secondGo)

	firstTS, err := providercatalog.RenderTS()
	require.NoError(t, err)
	secondTS, err := providercatalog.RenderTS()
	require.NoError(t, err)
	require.Equal(t, firstTS, secondTS)
}

func TestGeneratedSurfacesCarryProvenanceHeaders(t *testing.T) {
	goOut, err := providercatalog.RenderCapabilitiesGo()
	require.NoError(t, err)
	tsOut, err := providercatalog.RenderTS()
	require.NoError(t, err)
	for _, out := range []string{goOut, tsOut} {
		require.True(t, strings.HasPrefix(out, "// Code generated by api/cmd/gen-catalog"), "generated output must carry the codegen header")
		require.Contains(t, out, "api/internal/providercatalog/catalog.seed.json")
		require.Contains(t, out, "make catalog-gen")
		require.Contains(t, out, "render_test.go fails the build if this file is stale")
	}
}
