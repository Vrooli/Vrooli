package graph

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"prompt-manager/cli/internal/appctx"

	"github.com/vrooli/cli-core/cliutil"
)

type operatingMap struct {
	Teams  []operatingMapTeam  `json:"teams"`
	Topics []operatingMapTopic `json:"topics"`
	Edges  []operatingMapEdge  `json:"edges"`
}
type operatingMapTeam struct {
	ID          string `json:"id"`
	Label       string `json:"label"`
	GoalLinkage string `json:"goal_linkage"`
	Valid       bool   `json:"valid"`
}
type operatingMapTopic struct {
	ID    string `json:"id"`
	Label string `json:"label"`
}
type operatingMapEdge struct {
	From string `json:"from"`
	To   string `json:"to"`
}

// mapMember is overlaid from the relationship graph when --depth=member. The
// operating map itself is deliberately team+topic only (see
// api/graph/operating_map.go), so members are composed here rather than there.
type mapMember struct {
	Team  string
	Agent string
}

func cmdMap(ctx appctx.Context, args []string) error {
	fs := flag.NewFlagSet("map", flag.ContinueOnError)
	jsonOut := fs.Bool("json", false, "Output JSON")
	write := fs.Bool("write", false, "Write docs/agent-system/MAP.md")
	depth := fs.String("depth", "team", "Detail level: team | member")
	if err := cliutil.ParseInterspersed(fs, args); err != nil {
		return err
	}
	if *depth != "team" && *depth != "member" {
		return fmt.Errorf("--depth must be team or member, got %q", *depth)
	}

	var result operatingMap
	if err := ctx.Get("/operating-models/map", &result); err != nil {
		return fmt.Errorf("fetch operating map: %w", err)
	}
	if *jsonOut {
		return json.NewEncoder(os.Stdout).Encode(result)
	}

	var members []mapMember
	if *depth == "member" {
		var err error
		if members, err = fetchMapMembers(ctx); err != nil {
			return err
		}
	}

	rendered := renderOperatingMap(result, members)
	if *write {
		return os.WriteFile(filepath.Join("docs", "agent-system", "MAP.md"), []byte(rendered), 0o644)
	}
	fmt.Print(rendered)
	return nil
}

// fetchMapMembers reads team→agent membership from the relationship graph.
func fetchMapMembers(ctx appctx.Context) ([]mapMember, error) {
	var idx graphIndex
	if err := ctx.Get("/graph", &idx); err != nil {
		return nil, fmt.Errorf("fetch relationship graph: %w", err)
	}
	var members []mapMember
	for _, e := range idx.Graph.Edges {
		if e.Kind == "membership" {
			members = append(members, mapMember{Team: e.From, Agent: e.To})
		}
	}
	sort.Slice(members, func(i, j int) bool {
		if members[i].Team != members[j].Team {
			return members[i].Team < members[j].Team
		}
		return members[i].Agent < members[j].Agent
	})
	return members, nil
}

// mapIDAllocator assigns readable, collision-free Mermaid node ids.
//
// The previous renderer hex-encoded topic ids, which produced valid but
// unreadable Mermaid source (`X_6672696374696f6e...`). MAP.md is read by agents
// and humans as text far more often than it is rendered, so the id itself has
// to carry meaning.
type mapIDAllocator struct {
	assigned map[string]string
	taken    map[string]bool
}

func newMapIDAllocator() *mapIDAllocator {
	return &mapIDAllocator{assigned: map[string]string{}, taken: map[string]bool{}}
}

// id returns a stable Mermaid identifier for value, prefixed by kind.
func (a *mapIDAllocator) id(kind, value string) string {
	key := kind + "\x00" + value
	if existing, ok := a.assigned[key]; ok {
		return existing
	}
	base := kind + "_" + slugifyMapID(value)
	candidate := base
	for i := 2; a.taken[candidate]; i++ {
		candidate = fmt.Sprintf("%s_%d", base, i)
	}
	a.assigned[key] = candidate
	a.taken[candidate] = true
	return candidate
}

// slugifyMapID reduces an arbitrary topic or team value to Mermaid-safe
// characters while keeping it recognisable.
func slugifyMapID(value string) string {
	var b strings.Builder
	lastUnderscore := false
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
			lastUnderscore = false
		default:
			if !lastUnderscore {
				b.WriteByte('_')
				lastUnderscore = true
			}
		}
	}
	slug := strings.Trim(b.String(), "_")
	if slug == "" {
		slug = "node"
	}
	return slug
}

func renderOperatingMap(m operatingMap, members []mapMember) string {
	alloc := newMapIDAllocator()
	byTeam := map[string][]string{}
	for _, mem := range members {
		byTeam[mem.Team] = append(byTeam[mem.Team], mem.Agent)
	}

	var b strings.Builder
	b.WriteString("# Agent System Map\n\n")
	b.WriteString("> Generated by `prompt-manager graph map --write`; do not hand-edit.\n")
	b.WriteString("> Current sensor readings: `prompt-manager graph audit`.\n\n")

	b.WriteString("```mermaid\nflowchart LR\n")
	b.WriteString("  subgraph TEAMS[\"Teams\"]\n")
	for _, t := range m.Teams {
		id := alloc.id("team", t.ID)
		b.WriteString(fmt.Sprintf("    %s[\"%s\"]\n", id, t.Label))
		for _, agent := range byTeam[t.ID] {
			b.WriteString(fmt.Sprintf("    %s([\"%s\"])\n", alloc.id("member", agent), agent))
		}
	}
	b.WriteString("  end\n")

	b.WriteString("  subgraph TOPICS[\"Shared topic surfaces\"]\n")
	for _, topic := range m.Topics {
		b.WriteString(fmt.Sprintf("    %s[(\"%s\")]\n", alloc.id("topic", topic.ID), topic.Label))
	}
	b.WriteString("  end\n")

	for _, t := range m.Teams {
		for _, agent := range byTeam[t.ID] {
			b.WriteString(fmt.Sprintf("  %s --- %s\n", alloc.id("team", t.ID), alloc.id("member", agent)))
		}
	}
	for _, e := range m.Edges {
		b.WriteString(fmt.Sprintf("  %s --> %s\n", mapEndpointID(alloc, m, e.From), mapEndpointID(alloc, m, e.To)))
	}

	// Style invalid teams so a failing contract is visible in the picture
	// rather than only in the table below it.
	for _, t := range m.Teams {
		if !t.Valid {
			b.WriteString(fmt.Sprintf("  style %s stroke:#c0392b,stroke-width:3px\n", alloc.id("team", t.ID)))
		}
	}
	b.WriteString("```\n\n")

	b.WriteString("## Teams\n\n")
	header := "| Team | Goal linkage | Contract validation |\n|---|---|---|\n"
	if len(members) > 0 {
		header = "| Team | Members | Goal linkage | Contract validation |\n|---|---|---|---|\n"
	}
	b.WriteString(header)
	for _, t := range m.Teams {
		status := "valid"
		if !t.Valid {
			status = "**invalid**"
		}
		if len(members) > 0 {
			b.WriteString(fmt.Sprintf("| %s | %d | %s | %s |\n", t.Label, len(byTeam[t.ID]), t.GoalLinkage, status))
			continue
		}
		b.WriteString(fmt.Sprintf("| %s | %s | %s |\n", t.Label, t.GoalLinkage, status))
	}

	if len(members) > 0 {
		b.WriteString("\n## Members\n\n| Team | Member |\n|---|---|\n")
		for _, t := range m.Teams {
			for _, agent := range byTeam[t.ID] {
				b.WriteString(fmt.Sprintf("| %s | %s |\n", t.Label, agent))
			}
		}
	}
	return b.String()
}

// mapEndpointID resolves an edge endpoint to its allocated node id. Endpoints
// are team values or topic values; anything unrecognised is treated as a topic
// so an edge is never silently dropped.
func mapEndpointID(alloc *mapIDAllocator, m operatingMap, value string) string {
	for _, t := range m.Teams {
		if t.ID == value {
			return alloc.id("team", value)
		}
	}
	return alloc.id("topic", value)
}
