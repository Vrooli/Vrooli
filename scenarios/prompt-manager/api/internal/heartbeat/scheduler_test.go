func TestSchedulerScheduleStandard5FieldCron(t *testing.T) {
	exec := &captureExecutor{}
	configStore := &stubConfigStore{}
	scheduler := NewScheduler(exec, nil, configStore, nil)

	// Standard 5-field cron expressions generated by the UI must be accepted.
	cases := []struct {
		name     string
		schedule string
	}{
		{"daily at 10:45", "45 10 * * *"},
		{"every hour", "0 * * * *"},
		{"every 6 hours", "0 */6 * * *"},
		{"weekdays at 9am", "0 9 * * 1,2,3,4,5"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if err := scheduler.Schedule("team-1", "agent-1", tc.schedule); err != nil {
				t.Fatalf("Schedule(%q) should succeed for standard 5-field cron, got: %v", tc.schedule, err)
			}
			if next := scheduler.GetNextRun("team-1", "agent-1"); next == nil {
				t.Fatalf("GetNextRun should return a time after scheduling %q", tc.schedule)
			}
			scheduler.Unschedule("team-1", "agent-1")
		})
	}
}

func TestSchedulerGetNextRunsReturnsMultipleFutureTimes(t *testing.T) {
	exec := &captureExecutor{}
	configStore := &stubConfigStore{}
	scheduler := NewScheduler(exec, nil, configStore, nil)

	if err := scheduler.Schedule("team-1", "agent-1", "0 9 * * *"); err != nil {
		t.Fatalf("Schedule failed: %v", err)
	}

	runs := scheduler.GetNextRuns("team-1", "agent-1", 5)
	if len(runs) != 5 {
		t.Fatalf("expected 5 runs, got %d", len(runs))
	}

	// Each run must be strictly after the previous one.
	for i := 1; i < len(runs); i++ {
		if !runs[i].After(runs[i-1]) {
			t.Fatalf("run[%d] (%s) is not after run[%d] (%s)", i, runs[i], i-1, runs[i-1])
		}
	}

	scheduler.Unschedule("team-1", "agent-1")

	// Should return nil for unscheduled heartbeat.
	if runs := scheduler.GetNextRuns("team-1", "agent-1", 5); runs != nil {
		t.Fatalf("expected nil for unscheduled heartbeat, got %d runs", len(runs))
	}
}

