package projection

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedMarker = "<!-- GENERATED BY prompt-manager; projection owns this directory. -->"

type BasePack struct {
	Skills    []string `json:"skills"`
	MaxSkills int      `json:"maxSkills"`
	MaxTokens int      `json:"maxTokens"`
}

type Result struct {
	Target         string
	Skills         []string
	ResidentTokens int
	Removed        []string
}

// LoadBasePack reads the governed startup tier. It rejects a pack larger than
// the configured cap instead of silently turning a scoped projection into a
// full-corpus projection.
func LoadBasePack(path string) (BasePack, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return BasePack{}, err
	}
	var pack BasePack
	if err := json.Unmarshal(data, &pack); err != nil {
		return BasePack{}, fmt.Errorf("parse base pack: %w", err)
	}
	if pack.MaxSkills <= 0 || pack.MaxTokens <= 0 {
		return BasePack{}, fmt.Errorf("base pack must declare positive maxSkills and maxTokens")
	}
	if len(pack.Skills) > pack.MaxSkills {
		return BasePack{}, fmt.Errorf("base pack contains %d skills, ceiling is %d", len(pack.Skills), pack.MaxSkills)
	}
	return pack, nil
}

// Project writes only the named skills from one pack. Every file is generated
// and marked, and stale generated directories are removed while operator
// files are left untouched.
func Project(sourceRoot, target string, pack BasePack) (Result, error) {
	if filepath.Clean(target) == filepath.Clean(sourceRoot) || strings.HasPrefix(filepath.Clean(target), filepath.Clean(sourceRoot)+string(filepath.Separator)) {
		return Result{}, fmt.Errorf("projection target must not be inside skill source root: %s", target)
	}
	if pack.MaxSkills > 0 && len(pack.Skills) > pack.MaxSkills {
		return Result{}, fmt.Errorf("base pack contains %d skills, ceiling is %d", len(pack.Skills), pack.MaxSkills)
	}
	if err := os.MkdirAll(target, 0o755); err != nil {
		return Result{}, err
	}
	result := Result{Target: target, Skills: append([]string(nil), pack.Skills...)}
	sort.Strings(result.Skills)
	prepared := make(map[string]string, len(result.Skills))
	for _, id := range result.Skills {
		skillDir, err := resolveSkillDir(sourceRoot, id)
		if err != nil {
			return Result{}, err
		}
		if err := validateProjectionEligibility(skillDir); err != nil {
			return Result{}, fmt.Errorf("skill %s: %w", id, err)
		}
		content, err := os.ReadFile(filepath.Join(skillDir, "SKILL.md"))
		if err != nil {
			return Result{}, fmt.Errorf("read skill %s: %w", id, err)
		}
		if !hasFrontmatter(string(content)) {
			return Result{}, fmt.Errorf("skill %s has no valid frontmatter", id)
		}
		projected := ensureMarker(string(content))
		prepared[id] = projected
		result.ResidentTokens += estimateResidentTokens(projected)
	}
	if pack.MaxTokens > 0 && result.ResidentTokens > pack.MaxTokens {
		return Result{}, fmt.Errorf("projected base pack costs %d tokens, ceiling is %d", result.ResidentTokens, pack.MaxTokens)
	}
	generated := map[string]bool{}
	for _, id := range result.Skills {
		if err := os.MkdirAll(filepath.Join(target, id), 0o755); err != nil {
			return Result{}, err
		}
		if err := os.WriteFile(filepath.Join(target, id, "SKILL.md"), []byte(prepared[id]), 0o644); err != nil {
			return Result{}, err
		}
		generated[id] = true
	}
	entries, err := os.ReadDir(target)
	if err != nil {
		return Result{}, err
	}
	for _, entry := range entries {
		if !entry.IsDir() || generated[entry.Name()] {
			continue
		}
		candidate := filepath.Join(target, entry.Name(), "SKILL.md")
		if fileHasMarker(candidate) {
			if err := os.RemoveAll(filepath.Join(target, entry.Name())); err != nil {
				return Result{}, err
			}
			result.Removed = append(result.Removed, entry.Name())
		}
	}
	sort.Strings(result.Removed)
	return result, nil
}

// resolveSkillDir accepts both a direct skill root (used by focused callers)
// and the registry's pack root (packs/<pack>/<skill>). The latter is the
// canonical production source, so projection must not assume that every pack
// member lives directly below packs/.
func resolveSkillDir(sourceRoot, id string) (string, error) {
	direct := filepath.Join(sourceRoot, id)
	if info, err := os.Stat(direct); err == nil && info.IsDir() {
		return direct, nil
	} else if err != nil && !os.IsNotExist(err) {
		return "", err
	}
	entries, err := os.ReadDir(sourceRoot)
	if err != nil {
		return "", fmt.Errorf("read skill source root: %w", err)
	}
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		candidate := filepath.Join(sourceRoot, entry.Name(), id)
		if info, statErr := os.Stat(candidate); statErr == nil && info.IsDir() {
			return candidate, nil
		} else if statErr != nil && !os.IsNotExist(statErr) {
			return "", statErr
		}
	}
	return "", fmt.Errorf("skill %s not found under %s", id, sourceRoot)
}

// Imported skills are quarantined by sidecar metadata as well as pack order.
// Checking here protects callers that project a directory directly instead of
// resolving through FileSkillStore.List.
func validateProjectionEligibility(skillDir string) error {
	data, err := os.ReadFile(filepath.Join(skillDir, "skill.json"))
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	var metadata struct {
		Origin *struct {
			Kind   string `json:"kind"`
			Review struct {
				Verdict string `json:"verdict"`
			} `json:"review"`
		} `json:"origin"`
	}
	if err := json.Unmarshal(data, &metadata); err != nil {
		return fmt.Errorf("parse metadata: %w", err)
	}
	if metadata.Origin != nil && metadata.Origin.Kind == "imported" && metadata.Origin.Review.Verdict != "passed" {
		return fmt.Errorf("imported skill is quarantined (review verdict: %s)", metadata.Origin.Review.Verdict)
	}
	return nil
}

func hasFrontmatter(content string) bool {
	scanner := bufio.NewScanner(strings.NewReader(content))
	if !scanner.Scan() || strings.TrimSpace(scanner.Text()) != "---" {
		return false
	}
	name, description, closed := false, false, false
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "---" {
			closed = true
			break
		}
		if strings.HasPrefix(line, "name:") {
			name = strings.TrimSpace(strings.TrimPrefix(line, "name:")) != ""
		}
		if strings.HasPrefix(line, "description:") {
			description = strings.TrimSpace(strings.TrimPrefix(line, "description:")) != ""
		}
	}
	return closed && name && description
}

func ensureMarker(content string) string {
	if strings.Contains(content, generatedMarker) {
		return content
	}
	idx := strings.Index(content, "\n---")
	if idx < 0 {
		return content
	}
	idx += len("\n---")
	return content[:idx] + "\n" + generatedMarker + content[idx:]
}

func fileHasMarker(path string) bool {
	data, err := os.ReadFile(path)
	return err == nil && strings.Contains(string(data), generatedMarker)
}

// estimateResidentTokens models what native runtimes retain before activation:
// the skill name and description, not the instruction body. Counting the
// entire file would reject the governed base pack even though bodies are
// loaded lazily by the runtimes this projection serves.
func estimateResidentTokens(content string) int {
	lines := strings.Split(content, "\n")
	residentBytes := 0
	inFrontmatter := false
	for _, raw := range lines {
		line := strings.TrimSpace(raw)
		if line == "---" {
			if inFrontmatter {
				break
			}
			inFrontmatter = true
			continue
		}
		if !inFrontmatter {
			continue
		}
		for _, key := range []string{"name:", "description:"} {
			if strings.HasPrefix(line, key) {
				residentBytes += len(strings.TrimSpace(strings.TrimPrefix(line, key)))
				break
			}
		}
	}
	return (residentBytes + 3) / 4
}
