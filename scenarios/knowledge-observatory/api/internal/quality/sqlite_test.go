func newRepo(t *testing.T) *quality.SQLite {
	t.Helper()
	return quality.NewSQLite(dbtest.New(t, apidb.SchemaProviderFunc(quality.Schema)))
}

func ptr(v float64) *float64 { return &v }

// TestMetricRoundTripCoversEveryColumn writes every writable column and reads
// each one back. A silently lossy type translation (REAL truncation, a dropped
// timestamp) fails here rather than in production.
func TestMetricRoundTripCoversEveryColumn(t *testing.T) {
	repo := newRepo(t)
	ctx := context.Background()

	measured := time.Date(2026, 5, 6, 7, 8, 9, 0, time.UTC)
	in := quality.Metric{
		CollectionName: "vrooli_knowledge",
		Coherence:      ptr(0.25),
		Freshness:      ptr(0.5),
		Redundancy:     ptr(0.75),
		Coverage:       ptr(1),
		TotalEntries:   4321,
		MeasuredAt:     measured,
	}
	id, err := repo.InsertMetric(ctx, in)
	if err != nil {
		t.Fatalf("insert: %v", err)
	}
	if id == "" {
		t.Fatal("insert returned an empty id")
	}

	got, ok, err := repo.LatestMetric(ctx, "vrooli_knowledge")
	if err != nil || !ok {
		t.Fatalf("latest: ok=%v err=%v", ok, err)
	}

	if got.ID != id {
		t.Errorf("id = %q, want %q", got.ID, id)
	}
	if got.CollectionName != in.CollectionName {
		t.Errorf("collection_name = %q, want %q", got.CollectionName, in.CollectionName)
	}
	for _, c := range []struct {
		name      string
		got, want *float64
	}{
		{"coherence_score", got.Coherence, in.Coherence},
		{"freshness_score", got.Freshness, in.Freshness},
		{"redundancy_score", got.Redundancy, in.Redundancy},
		{"coverage_score", got.Coverage, in.Coverage},
	} {
		if c.got == nil || *c.got != *c.want {
			t.Errorf("%s = %v, want %v", c.name, c.got, *c.want)
		}
	}
	if got.TotalEntries != in.TotalEntries {
		t.Errorf("total_entries = %d, want %d", got.TotalEntries, in.TotalEntries)
	}
	// avg_quality is generated by the database, not written by the caller.
	if got.AvgQuality == nil || *got.AvgQuality != 0.625 {
		t.Errorf("avg_quality = %v, want 0.625 (the generated column)", got.AvgQuality)
	}
	if !got.MeasuredAt.UTC().Equal(measured) {
		t.Errorf("measured_at = %v, want %v", got.MeasuredAt.UTC(), measured)
	}
	if got.CreatedAt.IsZero() || got.UpdatedAt.IsZero() {
		t.Errorf("created_at/updated_at not defaulted: %v / %v", got.CreatedAt, got.UpdatedAt)
	}
}

// TestNullScoresSurviveTheCheckConstraint proves the CHECK constraints were
// translated with an explicit IS NULL arm. Postgres treats `NULL >= 0` as
// unknown and admits the row; a naive SQLite translation would too, but the
// explicit form documents the intent and this test locks it in.
func TestNullScoresSurviveTheCheckConstraint(t *testing.T) {
	repo := newRepo(t)
	if _, err := repo.InsertMetric(context.Background(), quality.Metric{
		CollectionName: "sparse",
		TotalEntries:   1,
	}); err != nil {
		t.Fatalf("insert with null scores: %v", err)
	}
}

