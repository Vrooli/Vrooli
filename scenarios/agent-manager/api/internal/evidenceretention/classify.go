// Package evidenceretention owns the bounded lifecycle of the shared effort
// evidence home (~/.vrooli/evidence/<effort>/...). Delivery and research
// workers write acceptance evidence there; alongside it they leave large
// regenerable intermediates: staged tool and runtime releases, copied service
// binaries, dependency trees and rendered frame sequences whose encoded video
// already exists.
//
// The package classifies those intermediates by file shape, never by
// directory name alone, and removes them only when the owning effort is
// terminal past a grace window (or an operator names the effort). Paths that
// any work record references are protected. Everything else (screenshots,
// reports, JSON receipts, final videos, packaged deliverables) is retained.
package evidenceretention

import (
	"bytes"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Class names a regenerable intermediate shape.
type Class string

const (
	// ClassPlatformRelease is a staged tool or resource release directory
	// such as tool_blender-renderer_linux_amd64 or kokoro_linux_amd64. The
	// owning tool/resource rebuilds it from its pinned public release.
	ClassPlatformRelease Class = "platform_release"
	// ClassReleaseArchive is a downloaded public release tarball (blender,
	// ffmpeg, electron, node, ...). The upstream URL regenerates it.
	ClassReleaseArchive Class = "release_archive"
	// ClassDependencyTree is node_modules, a Python virtualenv,
	// site-packages or __pycache__; package managers regenerate it.
	ClassDependencyTree Class = "dependency_tree"
	// ClassBuildBinary is a copied ELF executable or shared object (for
	// example a renderjob worker or service binary copied with a data tree).
	// Builds regenerate it; the receipts beside it keep its hash. Packaged
	// deliverables (AppImage) are not in this class.
	ClassBuildBinary Class = "build_binary"
	// ClassRenderFrames is a directory of raster frames whose encoded video
	// sits in the parent directory.
	ClassRenderFrames Class = "render_frames"
)

// minBinaryBytes keeps small helper binaries out of the report; the class
// exists for copied service and tool binaries measured in megabytes.
const minBinaryBytes = 1 << 20

var (
	platformReleaseDir = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]*_(linux|darwin|macos|windows)_(amd64|arm64|x64|x86_64|aarch64)$`)
	releaseArchive     = regexp.MustCompile(`(?i)^(blender|ffmpeg|electron|node|go|python|cmake|chromium|chrome|hyperframes)[-_v][^/]*\.(tar\.xz|tar\.gz|tgz|tar\.bz2|tar\.zst|zip)$`)
	framesDir          = regexp.MustCompile(`(?i)^(.*[-_])?frames([-_].*)?$`)
	frameImage         = map[string]bool{".png": true, ".jpg": true, ".jpeg": true, ".ppm": true, ".webp": true, ".exr": true, ".tif": true, ".tiff": true}
	encodedVideo       = map[string]bool{".mp4": true, ".webm": true, ".mov": true, ".mkv": true, ".m4v": true}
	elfMagic           = []byte{0x7f, 'E', 'L', 'F'}
)

// Candidate is one regenerable intermediate inside an effort's evidence.
type Candidate struct {
	// Path is relative to the evidence root, slash-separated.
	Path  string `json:"path"`
	Class Class  `json:"class"`
	Bytes int64  `json:"bytes"`
	// Files counts the regular files the candidate holds (1 for a file).
	Files       int    `json:"files"`
	Reason      string `json:"reason"`
	Protected   bool   `json:"protected"`
	ProtectedBy string `json:"protectedBy,omitempty"`
}

// sizer counts allocated bytes once per inode so hardlinked copies (common in
// copied data trees) are not double counted.
type sizer struct{ seen map[fileKey]bool }

func newSizer() *sizer { return &sizer{seen: map[fileKey]bool{}} }

func (s *sizer) file(info fs.FileInfo) int64 {
	if !info.Mode().IsRegular() {
		return 0
	}
	if key, ok := keyOf(info); ok {
		if s.seen[key] {
			return 0
		}
		s.seen[key] = true
	}
	return info.Size()
}

func (s *sizer) tree(path string) (int64, int) {
	var total int64
	files := 0
	_ = filepath.WalkDir(path, func(_ string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return nil
		}
		if info, err := d.Info(); err == nil {
			if info.Mode().IsRegular() {
				files++
			}
			total += s.file(info)
		}
		return nil
	})
	return total, files
}

// classifyDir returns the class of a directory, or "" when the directory is
// ordinary and its contents need individual inspection.
func classifyDir(path, name string) (Class, string) {
	switch {
	case platformReleaseDir.MatchString(name):
		return ClassPlatformRelease, "staged platform release; its tool or resource owner rebuilds it from the pinned release"
	case name == "node_modules":
		return ClassDependencyTree, "node_modules; the package manager reinstalls it from the lockfile"
	case name == "site-packages" || name == "__pycache__":
		return ClassDependencyTree, "python " + name + "; regenerated by installation or import"
	case name == ".venv" || name == "venv":
		if _, err := os.Stat(filepath.Join(path, "pyvenv.cfg")); err == nil {
			return ClassDependencyTree, "python virtualenv; recreated from requirements"
		}
	case framesDir.MatchString(name):
		if video := framesWithVideo(path); video != "" {
			return ClassRenderFrames, "rendered frames; encoded output " + video + " sits beside them"
		}
	}
	return "", ""
}

// framesWithVideo reports the encoded sibling video when dir holds only
// raster frames (at least two, no subdirectories) and its parent holds a
// video. A frames directory with notes, manifests or nested runs is evidence.
func framesWithVideo(dir string) string {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return ""
	}
	images := 0
	for _, e := range entries {
		if e.IsDir() || !frameImage[strings.ToLower(filepath.Ext(e.Name()))] {
			return ""
		}
		images++
	}
	if images < 2 {
		return ""
	}
	siblings, err := os.ReadDir(filepath.Dir(dir))
	if err != nil {
		return ""
	}
	for _, e := range siblings {
		if !e.IsDir() && encodedVideo[strings.ToLower(filepath.Ext(e.Name()))] {
			return e.Name()
		}
	}
	return ""
}

// classifyFile returns the class of a regular file, or "".
func classifyFile(path, name string, size int64) (Class, string) {
	if releaseArchive.MatchString(name) {
		return ClassReleaseArchive, "public release archive; downloadable from upstream"
	}
	lower := strings.ToLower(name)
	if size < minBinaryBytes || strings.HasSuffix(lower, ".appimage") {
		return "", ""
	}
	if isELF(path) {
		return ClassBuildBinary, "copied ELF binary; rebuilt from source, receipts keep its hash"
	}
	return "", ""
}

func isELF(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	head := make([]byte, 4)
	if _, err := io.ReadFull(f, head); err != nil {
		return false
	}
	return bytes.Equal(head, elfMagic)
}

// effortScan is the classification of one effort directory.
type effortScan struct {
	TotalBytes      int64
	ReferencedBytes int64
	Candidates      []Candidate
}

// scanEffort walks one effort directory. root is the evidence root; name is
// the effort directory name. Bytes are counted once per inode across the
// shared sizer.
func scanEffort(root, name string, refs *References, sz *sizer) effortScan {
	var out effortScan
	base := filepath.Join(root, name)
	_ = filepath.WalkDir(base, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel := relSlash(root, path)
		if d.IsDir() {
			if path == base {
				return nil
			}
			if class, reason := classifyDir(path, d.Name()); class != "" {
				bytes, files := sz.tree(path)
				out.TotalBytes += bytes
				out.Candidates = append(out.Candidates, protect(Candidate{Path: rel, Class: class, Bytes: bytes, Files: files, Reason: reason}, refs))
				return fs.SkipDir
			}
			return nil
		}
		if d.Type()&fs.ModeSymlink != 0 {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			return nil
		}
		bytes := sz.file(info)
		out.TotalBytes += bytes
		if class, reason := classifyFile(path, d.Name(), info.Size()); class != "" {
			out.Candidates = append(out.Candidates, protect(Candidate{Path: rel, Class: class, Bytes: bytes, Files: 1, Reason: reason}, refs))
			return nil
		}
		if refs.ReferencesRetained(rel) {
			out.ReferencedBytes += bytes
		}
		return nil
	})
	sort.Slice(out.Candidates, func(i, j int) bool { return out.Candidates[i].Path < out.Candidates[j].Path })
	return out
}

func protect(c Candidate, refs *References) Candidate {
	if by := refs.Protects(c.Path); by != "" {
		c.Protected, c.ProtectedBy = true, by
	}
	return c
}

func relSlash(root, path string) string {
	rel, err := filepath.Rel(root, path)
	if err != nil {
		return filepath.ToSlash(path)
	}
	return filepath.ToSlash(rel)
}
