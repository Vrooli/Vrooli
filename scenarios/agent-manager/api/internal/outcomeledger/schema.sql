-- One row per run: the facts every start path shares, its work unit and its
-- unit's outcome estimate. Rows are derived and rebuilt by the ledger job.
CREATE TABLE IF NOT EXISTS run_ledger_facts (
    run_id TEXT PRIMARY KEY,
    source_stamp TEXT NOT NULL DEFAULT '',
    path TEXT NOT NULL DEFAULT '',
    harness TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT '',
    live INTEGER NOT NULL DEFAULT 0,
    terminal_class TEXT NOT NULL DEFAULT '',
    stop_reason TEXT NOT NULL DEFAULT '',
    approval_state TEXT NOT NULL DEFAULT '',
    parent_run_id TEXT NOT NULL DEFAULT '',
    task_id TEXT NOT NULL DEFAULT '',
    goal_id TEXT NOT NULL DEFAULT '',
    session_key TEXT NOT NULL DEFAULT '',
    web_console_session TEXT NOT NULL DEFAULT '',
    workload_key TEXT NOT NULL DEFAULT '',
    source_run_ids TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT '',
    session_start TEXT NOT NULL DEFAULT '',
    first_activity_at TEXT NOT NULL DEFAULT '',
    last_activity_at TEXT NOT NULL DEFAULT '',
    requested_model TEXT NOT NULL DEFAULT '',
    actual_model TEXT NOT NULL DEFAULT '',
    effort TEXT NOT NULL DEFAULT '',
    mode_id TEXT NOT NULL DEFAULT '',
    mode_relation TEXT NOT NULL DEFAULT '',
    mode_basis TEXT NOT NULL DEFAULT '',
    mode_confidence REAL NOT NULL DEFAULT 0,
    selection_reason TEXT NOT NULL DEFAULT '',
    requests INTEGER NOT NULL DEFAULT 0,
    transcript_tool_calls INTEGER NOT NULL DEFAULT 0,
    fact_rows INTEGER NOT NULL DEFAULT 0,
    commands INTEGER NOT NULL DEFAULT 0,
    known_commands INTEGER NOT NULL DEFAULT 0,
    older_parser INTEGER NOT NULL DEFAULT 0,
    recall_evicted INTEGER NOT NULL DEFAULT 0,
    file_status TEXT NOT NULL DEFAULT '',
    file_fully_read INTEGER NOT NULL DEFAULT 0,
    edits INTEGER NOT NULL DEFAULT 0,
    validations_passed INTEGER NOT NULL DEFAULT 0,
    validations_failed INTEGER NOT NULL DEFAULT 0,
    last_validation TEXT NOT NULL DEFAULT '',
    last_validation_at TEXT NOT NULL DEFAULT '',
    operator_messages INTEGER NOT NULL DEFAULT 0,
    wall_ms INTEGER NOT NULL DEFAULT 0,
    active_ms INTEGER NOT NULL DEFAULT 0,
    attached_class TEXT NOT NULL DEFAULT '',
    linked_run_id TEXT NOT NULL DEFAULT '',
    work_unit_id TEXT NOT NULL DEFAULT '',
    link_kind TEXT NOT NULL DEFAULT '',
    link_confidence REAL NOT NULL DEFAULT 0,
    unit_outcome TEXT NOT NULL DEFAULT '',
    unit_source TEXT NOT NULL DEFAULT '',
    canary_arm TEXT NOT NULL DEFAULT '',
    arm TEXT NOT NULL DEFAULT '',
    arm_mode TEXT NOT NULL DEFAULT '',
    arm_basis TEXT NOT NULL DEFAULT '',
    arm_exception TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_run_ledger_activity ON run_ledger_facts(last_activity_at);
CREATE INDEX IF NOT EXISTS idx_run_ledger_unit ON run_ledger_facts(work_unit_id);

-- Usage mode periods as observed from the mode file, which keeps no history.
CREATE TABLE IF NOT EXISTS usage_mode_periods (
    id TEXT PRIMARY KEY,
    runner TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT '',
    profile TEXT NOT NULL DEFAULT '',
    targets TEXT NOT NULL DEFAULT '',
    started_at TEXT NOT NULL,
    expires_at TEXT NOT NULL DEFAULT '',
    ended_at TEXT NOT NULL DEFAULT '',
    kind TEXT NOT NULL DEFAULT '',
    label TEXT NOT NULL DEFAULT '',
    split REAL NOT NULL DEFAULT 0,
    session_opt_in INTEGER NOT NULL DEFAULT 0,
    block_days INTEGER NOT NULL DEFAULT 0
);
