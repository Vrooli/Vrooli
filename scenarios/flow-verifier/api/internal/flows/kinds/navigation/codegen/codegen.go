// Package codegen emits language-specific source artifacts from a
// compiled navigation graph. Phase 4 ships the TypeScript emitter only;
// routes.generated.ts is the single artifact consumed by
// reference-react-vite (and flow-verifier's own UI in Phase 5).
package codegen

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"flow-verifier/internal/flows/kinds/navigation/compile"
	"flow-verifier/internal/flows/kinds/navigation/contract"
)

// DefaultTypeScriptPath is the repo-relative destination the
// TypeScript emitter writes to when the caller does not override it.
// Phase 5 (self-adoption) will read from the spec's directory to
// derive a per-scenario path; until then this constant is the seam.
const DefaultTypeScriptPath = "ui/src/routes.generated.ts"

// TypeScript renders the routes.generated.ts module for graph g.
func TypeScript(g compile.Graph) ([]byte, error) {
	sorted := append([]contract.Route(nil), g.Contract.Routes...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })

	var b strings.Builder
	b.WriteString("// Code generated by flow-verifier. DO NOT EDIT.\n")
	b.WriteString("// Source: " + g.Contract.ContractPath + "\n")
	b.WriteString("// FlowId: " + g.Contract.FlowID + "\n\n")

	// ROUTES: snake_case id → const helper. For parameterised routes,
	// emit a function; otherwise a literal string.
	b.WriteString("export const ROUTES = {\n")
	for _, r := range sorted {
		params := pathParams(r.Path)
		camel := camelCase(r.ID)
		if len(params) == 0 {
			fmt.Fprintf(&b, "  %s: %q,\n", camel, r.Path)
			continue
		}
		// Path parameters are authored as TypeScript-valid identifiers in
		// the route path (e.g. ":flowId"); emit them verbatim rather than
		// running them through camelCase (which would lowercase them).
		argList := make([]string, len(params))
		for i, p := range params {
			argList[i] = p + ": string"
		}
		template := r.Path
		for _, p := range params {
			template = strings.ReplaceAll(template, ":"+p, "${"+p+"}")
		}
		fmt.Fprintf(&b, "  %s: (%s): string => `%s`,\n", camel, strings.Join(argList, ", "), template)
	}
	b.WriteString("} as const;\n\n")

	// ROUTE_PATTERNS: raw path strings keyed by camelCase id. Used by
	// React Router <Route path=> declarations where the literal pattern
	// (including ":param" placeholders) is needed.
	b.WriteString("export const ROUTE_PATTERNS = {\n")
	for _, r := range sorted {
		fmt.Fprintf(&b, "  %s: %q,\n", camelCase(r.ID), r.Path)
	}
	b.WriteString("} as const;\n\n")

	// Partitions. PUBLIC_ROUTES: routes with no `requires`. AUTH_REQUIRED_ROUTES:
	// routes whose `requires` references auth=logged_in.
	var public, authRequired []string
	for _, r := range sorted {
		switch {
		case r.Requires == "":
			public = append(public, r.ID)
		case strings.Contains(r.Requires, "auth=logged_in"):
			authRequired = append(authRequired, r.ID)
		}
	}
	writeStringArray(&b, "PUBLIC_ROUTES", routeIDsToCamel(public))
	writeStringArray(&b, "AUTH_REQUIRED_ROUTES", routeIDsToCamel(authRequired))

	// ROUTE_PATHS: parallel array of the raw path strings, for matchers
	// that need to enumerate every route (e.g. React Router config).
	allCamel := make([]string, len(sorted))
	for i, r := range sorted {
		allCamel[i] = camelCase(r.ID)
	}
	writeStringArray(&b, "ROUTE_IDS", allCamel)

	return []byte(b.String()), nil
}

func writeStringArray(b *strings.Builder, name string, ids []string) {
	fmt.Fprintf(b, "export const %s: readonly (keyof typeof ROUTES)[] = [", name)
	for i, id := range ids {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", id)
	}
	b.WriteString("];\n\n")
}

func routeIDsToCamel(ids []string) []string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = camelCase(id)
	}
	return out
}

var paramRE = regexp.MustCompile(`:([A-Za-z_][A-Za-z0-9_]*)`)

func pathParams(path string) []string {
	matches := paramRE.FindAllStringSubmatch(path, -1)
	if len(matches) == 0 {
		return nil
	}
	out := make([]string, 0, len(matches))
	for _, m := range matches {
		out = append(out, m[1])
	}
	return out
}

// camelCase converts snake_case identifiers to camelCase. Empty
// segments are skipped; an all-empty input returns "".
func camelCase(s string) string {
	parts := strings.Split(s, "_")
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i == 0 {
			b.WriteString(strings.ToLower(p))
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(strings.ToLower(p[1:]))
	}
	return b.String()
}
