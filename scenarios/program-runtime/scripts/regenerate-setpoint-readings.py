#!/usr/bin/env python3
"""Write program-runtime's current setpoint readings to docs/reference/setpoint-readings.md.

The input is the JSON envelope printed by ``program-runtime library run``.
The skill's section 2 table owns the row names; the generated file owns the dated readings.
The same envelope and date always produce the same file.
"""

import argparse
import datetime as dt
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "program-runtime-improve" / "SKILL.md"
OUT = ROOT / "docs" / "reference" / "setpoint-readings.md"
START = "## 2. Setpoint\n"
END = "\n### 3. Sensors"
HEADER = """# Setpoint readings (generated)

Generated by `scenarios/program-runtime/scripts/regenerate-setpoint-readings.py` from
`program-runtime.setpoint-read`; do not edit. Row names, sensors and bands are owned by
section 2 of `skills/program-runtime-improve/SKILL.md`. Refresh per
`docs/guides/setpoint-regeneration.md`.

| Row | Reading |
|---|---|
"""


def read_envelope(path: Path) -> dict:
    value = json.loads(path.read_text())
    if isinstance(value, dict) and isinstance(value.get("program"), dict):
        value = value["program"]
    if isinstance(value, dict) and isinstance(value.get("stdout"), str):
        value = json.loads(value["stdout"])
    if not isinstance(value, dict) or not isinstance(value.get("signals"), dict):
        raise ValueError("input does not contain a setpoint envelope")
    rows = value["signals"].get("rows")
    if not isinstance(rows, list):
        raise ValueError("setpoint envelope has no signals.rows list")
    return value


def generated_value(row: dict, date: str) -> str:
    if row.get("unavailable"):
        return f"{date}: unavailable ({row.get('reason') or 'unknown'})"
    reading = row.get("reading")
    if isinstance(reading, (dict, list)):
        rendered = json.dumps(reading, sort_keys=True, separators=(",", ":"))
    else:
        rendered = str(reading)
    band = "in band" if row.get("in_band") else "out of band"
    return f"{date}: {rendered} ({band})"


def skill_rows(skill: Path) -> list:
    text = skill.read_text()
    start = text.index(START) + len(START)
    section = text[start:text.index(END, start)]
    names = []
    for line in section.splitlines():
        if line.startswith("|"):
            name = line.strip().strip("|").split("|")[0].strip()
            if re.fullmatch(r"[a-z0-9][a-z0-9-]*", name):
                names.append(name)
    return names


def rewrite(skill: Path, envelope: dict, date: str, out: Path = OUT) -> None:
    values = {str(row.get("row")): generated_value(row, date) for row in envelope["signals"]["rows"]}
    listed = skill_rows(skill)
    missing = sorted(set(values) - set(listed))
    if missing:
        raise ValueError("skill is missing setpoint rows: " + ", ".join(missing))
    unreported = sorted(set(listed) - set(values))
    if unreported:
        raise ValueError("envelope does not report skill setpoint rows: " + ", ".join(unreported))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER + "".join(f"| {name} | {values[name].replace('|', chr(92) + '|')} |\n" for name in listed))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--envelope", type=Path, required=True, help="setpoint-read JSON output")
    parser.add_argument("--skill", type=Path, default=SKILL, help="improve skill that owns the row names")
    parser.add_argument("--out", type=Path, default=OUT, help="generated readings file")
    parser.add_argument("--date", default=dt.date.today().isoformat(), help="observation date, default today")
    args = parser.parse_args()
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.date):
        raise SystemExit("--date must be YYYY-MM-DD")
    rewrite(args.skill, read_envelope(args.envelope), args.date, args.out)


if __name__ == "__main__":
    main()
