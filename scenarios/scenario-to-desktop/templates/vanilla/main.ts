/**
 * Check if the server is ready to accept requests.
 *
 * DOC: docs/internal/SEAMS.md#server-readiness
 *
 * Unlike the previous implementation, this function:
 * - Validates HTTP status codes (only accepts 2xx responses)
 * - Reports progress for UI feedback
 * - Provides detailed error messages for debugging
 *
 * @param url - URL to check for readiness
 * @param timeout - Maximum time to wait in milliseconds
 * @throws Error if server doesn't become ready within timeout
 */
async function checkServerReady(url: string, timeout: number): Promise<void> {
    const httpClient = createElectronReadinessChecker(electronNet);
    const config: ReadinessConfig = {
        url,
        timeoutMs: timeout,
        pollIntervalMs: APP_CONFIG.SERVER_CHECK_INTERVAL_MS,
        acceptableStatusCodes: DEFAULT_READINESS_CONFIG.acceptableStatusCodes,
        acceptAny2xx: true, // Only accept 2xx status codes as "ready"
    };

    const result = await checkServerReadiness(
        httpClient,
        config,
        undefined, // Use real timer
        (attempt, elapsed) => {
            // Log progress every 10 attempts (~5 seconds)
            if (attempt % 10 === 0) {
                console.log(`[Desktop App] Server check attempt ${attempt}, elapsed: ${elapsed}ms`);
            }
            // Update splash status if available
            if (splashManager) {
                splashManager.updateStatus({
                    phase: "loading-ui",
                    message: `Waiting for server... (${Math.round(elapsed / 1000)}s)`,
                    progress: Math.min(90, Math.round((elapsed / timeout) * 100)),
                });
            }
        }
    );

    if (result.ready) {
        console.log(`[Desktop App] Server ready at ${url} (status: ${result.statusCode}, took: ${result.durationMs}ms)`);
        void recordTelemetry("server_ready", {
            url,
            statusCode: result.statusCode,
            durationMs: result.durationMs,
        });
    } else {
        // Build a detailed error message that includes status code if we got one
        let errorMsg: string;
        if (result.statusCode !== undefined) {
            // We got a response but with wrong status code
            errorMsg = `Server at ${url} returned status ${result.statusCode} (expected 2xx). ${result.error ?? ""}`.trim();
        } else {
            // Connection failure or timeout
            errorMsg = result.error ?? `Server not ready at ${url} within ${timeout}ms`;
        }

        console.error(`[Desktop App] ${errorMsg}`);
        void recordTelemetry("dependency_unreachable", {
            url,
            timeoutMs: timeout,
            lastStatusCode: result.statusCode,
            error: result.error,
        }, "error");
        throw new Error(errorMsg);
    }
}

async function runSmokeTest(): Promise<void> {
    SmokeTestProtocol.init();
    await initializeTelemetry();
    await recordTelemetry("smoke_test_started", {
        deploymentMode: APP_CONFIG.DEPLOYMENT_MODE,
        serverType: APP_CONFIG.SERVER_TYPE,
    });

    let success = false;
    let failureMessage = "";
    let runtimeUrl = "";

    try {
        if (isBundledMode) {
            const bundleResolution = await resolveBundleRootWithDiagnostics();
            if (!bundleResolution.found || !bundleResolution.path) {
                const pathsChecked = bundleResolution.candidatesChecked.join(", ");
                const errorMsg = `Bundled payload is missing. Checked: [${pathsChecked}]. Fix: Add bundle to extraResources in package.json`;
                SmokeTestProtocol.error("config", errorMsg);
                throw new Error(errorMsg);
            }
            const bundleRoot = bundleResolution.path;
            const manifestPath = path.join(bundleRoot, "bundle.json");
            if (!(await pathExists(manifestPath))) {
                SmokeTestProtocol.error("config", `Bundled manifest missing at ${manifestPath}`);
                throw new Error(`Bundled manifest missing at ${manifestPath}`);
            }
            const validationResult = await validateBundlePreFlight(bundleRoot, manifestPath);
            if (!validationResult.valid) {
                const errorDetails = formatValidationErrors(validationResult);
                SmokeTestProtocol.error("validation", `Bundle validation failed: ${errorDetails}`);
                throw new Error(`Bundle validation failed: ${errorDetails}`);
            }
            if (!BUNDLED_RUNTIME.SUPPORTED) {
                SmokeTestProtocol.error("config", "Bundled runtime is not supported in this build");
                throw new Error("Bundled runtime is not supported in this build");
            }
            runtimeUrl = await startBundledRuntime();
            SmokeTestProtocol.stage.uiServerCheck();
            await checkServerReady(runtimeUrl, smokeTestTimeoutMs);

            // POST-SUCCESS STABILITY CHECK
            // DOC: docs/internal/SEAMS.md#smoketest-stability-validation
            // Wait a short period after server ready to catch runtime crashes that occur
            // after initial health checks pass. This catches the race condition where
            // the runtime exits with code 1 immediately after responding to health checks.
            console.log(`[Smoke Test] Server ready, performing ${POST_SUCCESS_STABILITY_DELAY_MS}ms stability check...`);
            const stabilityStartTime = Date.now();
            while (Date.now() - stabilityStartTime < POST_SUCCESS_STABILITY_DELAY_MS) {
                // Check if runtime has exited during stability period
                if (hasRuntimeExitedUnexpectedly()) {
                    const exitInfo = runtimeExitInfo;
                    const errorMsg = exitInfo.stderr.trim()
                        ? `Runtime crashed during stability check (exit ${exitInfo.code}): ${exitInfo.stderr.slice(0, 200)}`
                        : `Runtime crashed during stability check with exit code ${exitInfo.code}`;
                    console.error(`[Smoke Test] ${errorMsg}`);
                    SmokeTestProtocol.error("runtime", errorMsg);
                    throw new Error(errorMsg);
                }
                await new Promise(resolve => setTimeout(resolve, STABILITY_CHECK_INTERVAL_MS));
            }
            console.log("[Smoke Test] Stability check passed - runtime remained stable");
        } else if (APP_CONFIG.SERVER_TYPE === "static") {
            const staticPath = path.resolve(app.getAppPath(), APP_CONFIG.SERVER_PATH);
            if (!(await pathExists(staticPath))) {
                SmokeTestProtocol.error("config", `Static UI missing at ${staticPath}`);
                throw new Error(`Static UI missing at ${staticPath}`);
            }
        } else {
            runtimeUrl = SERVER_URL;
            SmokeTestProtocol.stage.uiServerCheck();
            await checkServerReady(SERVER_URL, smokeTestTimeoutMs);
        }

        // Final runtime check before declaring success
        if (isBundledMode && hasRuntimeExitedUnexpectedly()) {
            const exitInfo = runtimeExitInfo;
            const errorMsg = exitInfo.stderr.trim()
                ? `Runtime crashed before completion (exit ${exitInfo.code}): ${exitInfo.stderr.slice(0, 200)}`
                : `Runtime crashed before completion with exit code ${exitInfo.code}`;
            console.error(`[Smoke Test] ${errorMsg}`);
            SmokeTestProtocol.error("runtime", errorMsg);
            throw new Error(errorMsg);
        }

        SmokeTestProtocol.ready();
        success = true;
    } catch (error) {
        const errorMsg = String(error);
        failureMessage = errorMsg;
        // Emit structured error for network-related failures if not already emitted
        if (errorMsg.includes("not ready") || errorMsg.includes("timeout") || errorMsg.includes("ECONNREFUSED")) {
            SmokeTestProtocol.error("network", errorMsg);
        } else if (!errorMsg.includes("SMOKE_TEST_ERROR")) {
            // Only emit runtime error if we haven't already emitted a structured error
            SmokeTestProtocol.error("runtime", errorMsg);
        }
    } finally {
        if (isBundledMode) {
            await shutdownRuntime();
        }
    }

    if (success) {
        await recordTelemetry("smoke_test_passed", { serverUrl: runtimeUrl || SERVER_URL });
    } else {
        await recordTelemetry("smoke_test_failed", { error: failureMessage }, "error");
    }
    SmokeTestProtocol.result(success, failureMessage);

    if (smokeTestUploadURL && telemetryFilePath) {
        try {
            await uploadTelemetryFile(telemetryFilePath, smokeTestUploadURL, "smoke-test", true);
            SmokeTestProtocol.upload(true);
        } catch (error) {
            SmokeTestProtocol.upload(false, String(error));
        }
    }

    SmokeTestProtocol.exit();
    app.exit(success ? 0 : 1);
}

