async function isPortFree(host: string, port: number): Promise<boolean> {
    return new Promise((resolve) => {
        const server = nodeNet.createServer();
        server.once("error", () => resolve(false));
        server.once("listening", () => {
            server.close(() => resolve(true));
        });
        server.listen(port, host);
    });
}

async function findEphemeralPort(host: string): Promise<number> {
    return new Promise((resolve, reject) => {
        const server = nodeNet.createServer();
        server.once("error", reject);
        server.listen(0, host, () => {
            const address = server.address();
            const port = typeof address === "object" && address ? address.port : 0;
            server.close(() => resolve(port));
        });
    });
}

async function allocateIpcPort(host: string, preferred: number): Promise<{ port: number; changed: boolean }> {
    const port = await findEphemeralPort(host);
    return { port, changed: port !== preferred };
}

/** Result of bundle root resolution with diagnostic context */
interface BundleResolutionResult {
    found: boolean;
    path: string | null;
    candidatesChecked: string[];
}

async function resolveBundleRoot(): Promise<string | null> {
    const result = await resolveBundleRootWithDiagnostics();
    return result.path;
}

/**
 * Resolves the bundle root directory with full diagnostic information.
 * Returns the paths checked for debugging when bundle is not found.
 */
async function resolveBundleRootWithDiagnostics(): Promise<BundleResolutionResult> {
    const bundleRoot = BUNDLED_RUNTIME.ROOT || "bundle";
    const candidates = [
        path.join(process.resourcesPath, bundleRoot),
        path.join(app.getAppPath(), bundleRoot),
    ];

    for (const candidate of candidates) {
        if (await pathExists(candidate)) {
            console.log(`[Desktop App] Bundle found at: ${candidate}`);
            return { found: true, path: candidate, candidatesChecked: candidates };
        }
    }

    // Log diagnostic info when bundle is not found
    console.error(`[Desktop App] Bundle not found. Checked locations:`);
    for (const candidate of candidates) {
        console.error(`  - ${candidate}`);
    }
    console.error(`[Desktop App] This usually means the bundle directory was not included in electron-builder extraResources.`);
    console.error(`[Desktop App] Fix: Add to package.json: "extraResources": [{ "from": "bundle", "to": "bundle" }]`);

    return { found: false, path: null, candidatesChecked: candidates };
}

async function waitForFile(filePath: string, timeoutMs = 15000): Promise<void> {
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
        if (await pathExists(filePath)) {
            return;
        }
        await new Promise((resolve) => setTimeout(resolve, 150));
    }
    // Emit structured error before throwing so smoke test service can capture it
    if (isSmokeTest) {
        SmokeTestProtocol.error("runtime", `Timed out waiting for file: ${filePath}`);
    }
    throw new Error(`file not found within timeout: ${filePath}`);
}

function normalizeBundlePath(bundleRoot: string, rel: string): string {
    return path.join(bundleRoot, rel.replace(/\\/g, path.sep));
}

async function findChromiumPath(bundleRoot: string, manifestPath: string): Promise<string | null> {
    const candidates: string[] = [];

    try {
        const raw = await fs.readFile(manifestPath, "utf-8");
        const manifest = JSON.parse(raw) as { services?: Array<{ assets?: Array<{ path: string }>; env?: Record<string, string> }> };
        for (const svc of manifest.services || []) {
            for (const asset of svc.assets || []) {
                if (asset.path?.toLowerCase().includes("chromium") || asset.path?.toLowerCase().includes("playwright")) {
                    candidates.push(asset.path);
                }
            }
            for (const value of Object.values(svc.env || {})) {
                if (typeof value === "string" && value.toLowerCase().includes("chromium")) {
                    candidates.push(value);
                }
            }
        }
    } catch (error) {
        console.warn("[Desktop App] Unable to parse bundle manifest for Chromium detection", error);
    }

    for (const rel of candidates) {
        const candidate = path.isAbsolute(rel) ? rel : normalizeBundlePath(bundleRoot, rel);
        if (await pathExists(candidate)) {
            return candidate;
        }
    }

    const electronCandidates: string[] = [process.execPath];
    if (process.platform === "darwin") {
        electronCandidates.push(
            path.join(process.resourcesPath, "..", "Frameworks", "Electron Framework.framework", "Versions", "Current", "Helpers", "Electron Helper (Renderer).app", "Contents", "MacOS", "Electron Helper (Renderer)"),
            path.join(process.resourcesPath, "..", "Frameworks", "Electron Framework.framework", "Versions", "Current", "Resources", "electron")
        );
    } else if (process.platform === "win32") {
        electronCandidates.push(path.join(path.dirname(process.execPath), "chrome.exe"));
    } else {
        electronCandidates.push(path.join(path.dirname(process.execPath), "chrome"));
    }

    for (const candidate of electronCandidates) {
        if (await pathExists(candidate)) {
            return candidate;
        }
    }

    return null;
}

async function startBundledRuntime(): Promise<string> {
    // Emit granular stage marker for smoke test diagnostics
    if (isSmokeTest) SmokeTestProtocol.stage.bundleResolving();
    updateSplashStatus("validating-bundle", "Resolving bundle...");

    const bundleResolution = await resolveBundleRootWithDiagnostics();
    if (!bundleResolution.found || !bundleResolution.path) {
        const pathsChecked = bundleResolution.candidatesChecked.join(", ");
        throw new Error(`Bundled payload is missing. Checked: [${pathsChecked}]. Fix: Add bundle to extraResources in package.json, then regenerate or reinstall the desktop app.`);
    }
    const bundleRoot = bundleResolution.path;

    const manifestPath = path.join(bundleRoot, "bundle.json");
    if (!(await pathExists(manifestPath))) {
        throw new Error(`Bundled manifest missing at ${manifestPath}`);
    }

    updateSplashStatus("validating-bundle", "Reading bundle manifest...", 10);

    // Ensure IPC port is free; stage a writable manifest copy for runtime/shims.
    let manifestContent: any;
    try {
        manifestContent = JSON.parse(await fs.readFile(manifestPath, "utf-8"));
    } catch (err) {
        throw new Error(`Failed to read bundle manifest: ${String(err)}`);
    }

    updateSplashStatus("allocating-ports", "Allocating network ports...", 15);

    const ipcHost = manifestContent?.ipc?.host || "127.0.0.1";
    const preferredPort = Number(manifestContent?.ipc?.port) || 39200;
    const { port: runtimePort, changed } = await allocateIpcPort(ipcHost, preferredPort);
    if (changed) {
        console.log(`[Desktop App] IPC port ${preferredPort} was busy; using ${runtimePort} instead`);
    }
    manifestContent.ipc = manifestContent.ipc || {};
    manifestContent.ipc.port = runtimePort;
    RUNTIME_CONTROL.PORT = runtimePort;

    const appData = path.join(app.getPath("userData"), "runtime");
    await fs.mkdir(appData, { recursive: true });
    runtimeAppDataRoot = appData;

    const stagedManifestPath = path.join(appData, "bundle.json");
    await fs.writeFile(stagedManifestPath, JSON.stringify(manifestContent, null, 2), "utf-8");
    const portPath = path.join(appData, "runtime", "ipc_port");
    await fs.mkdir(path.dirname(portPath), { recursive: true });
    await fs.writeFile(portPath, `${runtimePort}`, "utf-8");

    // Pre-flight validation: check manifest structure and required files before spawning runtime
    console.log("[Desktop App] Performing pre-flight bundle validation...");
    const validationResult = await validateBundlePreFlight(bundleRoot, stagedManifestPath);
    if (!validationResult.valid) {
        const errorDetails = formatValidationErrors(validationResult);
        await recordTelemetry("bundle_validation_failed", {
            errors: validationResult.errors,
            missingBinaries: validationResult.missingBinaries,
            missingAssets: validationResult.missingAssets,
        });
        throw new Error(`Bundle validation failed:\n${errorDetails}\n\nThe bundle may be corrupted or incomplete. Try regenerating or reinstalling the desktop app.`);
    }
    console.log("[Desktop App] Pre-flight bundle validation passed");

    const runtimePath = path.join(
        bundleRoot,
        "runtime",
        runtimePlatformKey(),
        process.platform === "win32" ? "runtime.exe" : "runtime",
    );
    if (!(await pathExists(runtimePath))) {
        throw new Error(`Bundled runtime binary not found for this platform (${runtimePath})`);
    }

    const tokenRel = BUNDLED_RUNTIME.TOKEN_REL || "runtime/auth-token";
    const tokenPath = path.join(appData, tokenRel);
    RUNTIME_CONTROL.TOKEN_PATH_ENV = tokenPath;

    const args = [
        "--manifest",
        stagedManifestPath,
        "--bundle-root",
        bundleRoot,
        "--app-data",
        appData,
        "--dry-run=false",
    ];

    const chromiumPath = await findChromiumPath(bundleRoot, manifestPath);
    const runtimeEnv: Record<string, string | undefined> = { ...process.env };
    if (chromiumPath && !runtimeEnv.ELECTRON_CHROMIUM_PATH) {
        runtimeEnv.ELECTRON_CHROMIUM_PATH = chromiumPath;
    }
    // Bundled binaries cannot rebuild themselves - skip staleness checks that look for go.mod
    runtimeEnv.VROOLI_API_SKIP_STALE_CHECK = "true";

    // Bridge to Vrooli lifecycle - bundled Go binaries require these env vars
    // DOC: docs/internal/SEAMS.md#port-environment-seam
    runtimeEnv.VROOLI_LIFECYCLE_MANAGED = "true";
    runtimeEnv.VROOLI_DESKTOP_MODE = "true";

    // Set data directory for scenarios that use VROOLI_DATA for storage
    // This maps to the app's userData directory which is isolated per-app
    runtimeEnv.VROOLI_DATA = appData;
    console.log(`[Desktop App] Setting VROOLI_DATA=${appData}`);

    // NOTE: The following Vrooli lifecycle env vars are intentionally NOT set:
    //
    // - VROOLI_ROOT: Points to the Vrooli monorepo root in development. Not applicable
    //   for standalone desktop apps. Scenarios should check VROOLI_DESKTOP_MODE and
    //   handle the standalone case (e.g., prompt user to select paths via UI).
    //
    // - SCENARIO_ROOT: Points to the scenario directory in the monorepo. Not applicable
    //   because the scenario is bundled into the app, not in a directory structure.
    //   Use BUNDLE_ROOT (set by runtime) if you need to reference bundled assets.

    // Set ALL port env vars from PORTS config
    // This is critical for Go binaries that call requireEnv("API_PORT"), etc.
    for (const [portKey, portConfig] of Object.entries(PORTS)) {
        if (portConfig.envVar && portConfig.port) {
            runtimeEnv[portConfig.envVar] = String(portConfig.port);
            console.log(`[Desktop App] Setting ${portConfig.envVar}=${portConfig.port} (port: ${portKey})`);
        }
    }

    // Reset module-level runtime exit tracking before starting new runtime
    resetRuntimeExitTracking();

    // Always capture stderr for debugging (previously only in smoke test mode)
    // This enables better error messages in splash screen and telemetry
    const stdioCfg: "inherit" | ["inherit", "inherit", "pipe"] = ["inherit", "inherit", "pipe"];

    // Emit granular stage marker for smoke test diagnostics
    if (isSmokeTest) SmokeTestProtocol.stage.runtimeStarting();

    updateSplashStatus("starting-runtime", "Starting runtime services...", 30);

    runtimeProcess = spawn(runtimePath, args, {
        stdio: stdioCfg,
        env: runtimeEnv,
    });

    // Track stderr for error reporting (used by both smoke test and normal mode)
    let stderrErrorEmitted = false;

    // Patterns that indicate specific runtime errors - emit structured markers for these
    const runtimeErrorPatterns: Array<{ pattern: RegExp; kind: "config" | "network" | "runtime" | "validation"; message: string }> = [
        { pattern: /no go\.mod|staleness check/i, kind: "config", message: "Go binary staleness check failed - VROOLI_API_SKIP_STALE_CHECK should be set" },
        { pattern: /ECONNREFUSED|connection refused/i, kind: "network", message: "Connection refused - target service may not be running" },
        { pattern: /ENOENT|no such file/i, kind: "config", message: "Required file or binary not found in bundle" },
        { pattern: /permission denied|EACCES/i, kind: "runtime", message: "Permission denied accessing file or port" },
        { pattern: /address already in use|EADDRINUSE/i, kind: "network", message: "Port already in use - another instance may be running" },
    ];

    // Always capture stderr for debugging (not just in smoke test mode)
    if (runtimeProcess.stderr) {
        runtimeProcess.stderr.on("data", (data: Buffer) => {
            const chunk = data.toString();
            // Accumulate stderr in module-level tracking for error messages
            runtimeExitInfo.stderr += chunk;
            // Also write to process stderr so it appears in logs
            process.stderr.write(chunk);

            // In smoke test mode, emit structured error for first matching pattern
            if (isSmokeTest && !stderrErrorEmitted) {
                for (const { pattern, kind, message } of runtimeErrorPatterns) {
                    if (pattern.test(chunk)) {
                        SmokeTestProtocol.error(kind, message);
                        stderrErrorEmitted = true;
                        break;
                    }
                }
            }
        });
    }

    runtimeProcess.on("exit", (code, signal) => {
        // Update module-level tracking
        runtimeExitInfo.exited = true;
        runtimeExitInfo.code = code;
        runtimeExitInfo.signal = signal;
        runtimeExitInfo.exitedAt = new Date();

        void recordTelemetry("bundled_runtime_exit", { code, signal });

        // In smoke test mode, emit structured error if runtime crashed unexpectedly
        if (isSmokeTest && code !== 0 && code !== null) {
            const errorMsg = runtimeExitInfo.stderr.trim()
                ? `Bundled runtime crashed (exit ${code}): ${runtimeExitInfo.stderr.slice(0, 200)}`
                : `Bundled runtime crashed with exit code ${code}`;
            SmokeTestProtocol.error("runtime", errorMsg);
        }
    });

    // Emit granular stage marker for smoke test diagnostics
    if (isSmokeTest) SmokeTestProtocol.stage.waitingForToken();
    updateSplashStatus("waiting-for-token", "Waiting for authentication token...", 40);
    // Log the expected token path for debugging token mismatch issues
    console.log(`[Desktop App] Waiting for runtime auth token at: ${tokenPath}`);
    console.log(`[Desktop App] Token path config: BUNDLED_RUNTIME.TOKEN_REL=${BUNDLED_RUNTIME.TOKEN_REL}`);
    await waitForFile(tokenPath, APP_CONFIG.SERVER_CHECK_TIMEOUT_MS);

    // Emit granular stage marker for smoke test diagnostics
    if (isSmokeTest) SmokeTestProtocol.stage.runtimeHealthz();
    updateSplashStatus("checking-health", "Checking service health...", 50);
    await waitForRuntimeControl(APP_CONFIG.SERVER_CHECK_TIMEOUT_MS);

    // Comprehensive validation via runtime API (includes checksum verification)
    try {
        const runtimeValidation = await validateBundleViaRuntime();
        if (runtimeValidation && !runtimeValidation.valid) {
            const checksumErrors = runtimeValidation.invalid_checksums?.length || 0;
            const otherErrors = (runtimeValidation.errors?.length || 0) - checksumErrors;

            // Log validation issues
            console.warn("[Desktop App] Runtime validation found issues:", runtimeValidation);
            await recordTelemetry("runtime_validation_issues", {
                valid: false,
                errorCount: runtimeValidation.errors?.length || 0,
                warningCount: runtimeValidation.warnings?.length || 0,
                checksumMismatches: checksumErrors,
            });

            // If there are critical errors (beyond checksum mismatches), warn the user
            if (otherErrors > 0) {
                const errorMessages = runtimeValidation.errors
                    ?.filter(e => e.code !== "checksum_mismatch")
                    .map(e => e.message)
                    .join("\n") || "Unknown validation errors";
                console.error("[Desktop App] Critical validation errors:", errorMessages);
            }
        } else if (runtimeValidation?.valid) {
            console.log("[Desktop App] Runtime bundle validation passed");
        }
    } catch (error) {
        console.warn("[Desktop App] Runtime validation check failed (non-fatal):", error);
    }

    await ensureRuntimeSecretsIfNeeded();

    // Emit granular stage marker for smoke test diagnostics
    if (isSmokeTest) SmokeTestProtocol.stage.runtimeReadyz();
    updateSplashStatus("checking-ready", "Verifying services are ready...", 60);

    const readyDeadline = Date.now() + APP_CONFIG.SERVER_CHECK_TIMEOUT_MS;
    while (Date.now() < readyDeadline) {
        try {
            const ready = await runtimeRequest<{ ready: boolean }>("/readyz");
            if ((ready as any)?.ready) {
                break;
            }
        } catch {
            // runtime may still be starting
        }
        await new Promise((resolve) => setTimeout(resolve, 350));
    }

    // Emit granular stage marker for smoke test diagnostics
    if (isSmokeTest) SmokeTestProtocol.stage.runtimePorts();
    updateSplashStatus("discovering-ports", "Discovering service endpoints...", 70);

    const ports = await runtimeRequest<{ services: Record<string, Record<string, number>> }>("/ports");
    const serviceId = BUNDLED_RUNTIME.UI_SERVICE || Object.keys((ports as any).services || {})[0];
    const portName = BUNDLED_RUNTIME.UI_PORT_NAME || "http";
    const svcPorts = (ports as any).services?.[serviceId];
    const port = svcPorts?.[portName];
    if (!serviceId || !port) {
        throw new Error("Bundled runtime started but did not expose a UI port");
    }

    updateSplashStatus("loading-ui", "Starting user interface...", 80);

    const url = `http://127.0.0.1:${port}/`;
    await recordTelemetry("bundled_runtime_ready", {
        bundleRoot,
        serviceId,
        portName,
        port,
    });
    void autoUploadTelemetryIfConfigured("startup");
    return url;
}

async function shutdownRuntime(): Promise<void> {
    if (RUNTIME_CONTROL.ENABLED) {
        void autoUploadTelemetryIfConfigured("shutdown");
        try {
            await runtimeRequest("/shutdown", { method: "POST" });
        } catch (error) {
            console.warn("[Desktop App] Failed to request runtime shutdown", error);
        }
    }
    if (runtimeProcess) {
        try {
            runtimeProcess.kill();
        } catch {
            // ignore
        }
        runtimeProcess = null;
    }
}

async function startScenarioServer() {
    if (APP_CONFIG.SERVER_TYPE === "external") {
        console.log(`[Desktop App] Using external server: ${APP_CONFIG.SERVER_PATH}`);
        void recordTelemetry("external_server_mode", {
            serverPath: APP_CONFIG.SERVER_PATH,
        });
        return;
    }

    if (APP_CONFIG.SERVER_TYPE === "static") {
        console.log("[Desktop App] Using static files, no server to start");
        return;
    }

    const serverPath = path.resolve(app.getAppPath(), APP_CONFIG.SERVER_PATH);
    console.log(`[Desktop App] Starting scenario server: ${serverPath}`);

    try {
        // In smoke test mode, capture stderr for error reporting
        const serverStdioCfg: "inherit" | ["inherit", "inherit", "pipe"] = isSmokeTest
            ? ["inherit", "inherit", "pipe"]
            : "inherit";
        let serverStderr = "";

        if (APP_CONFIG.SERVER_TYPE === "node") {
            serverProcess = fork(serverPath, [], {
                env: {
                    ...process.env,
                    PORT: APP_CONFIG.SERVER_PORT.toString(),
                    DESKTOP_MODE: "true",
                    API_ENDPOINT: APP_CONFIG.API_ENDPOINT,
                },
                stdio: serverStdioCfg,
            });
        } else if (APP_CONFIG.SERVER_TYPE === "executable") {
            serverProcess = spawn(serverPath, [], {
                env: {
                    ...process.env,
                    PORT: APP_CONFIG.SERVER_PORT.toString(),
                    DESKTOP_MODE: "true",
                    API_ENDPOINT: APP_CONFIG.API_ENDPOINT,
                },
                stdio: serverStdioCfg,
            });
        }

        void recordTelemetry("local_server_started", {
            mode: APP_CONFIG.SERVER_TYPE,
            serverPath,
        });

        if (serverProcess) {
            // Capture stderr in smoke test mode
            if (isSmokeTest && serverProcess.stderr) {
                serverProcess.stderr.on("data", (data: Buffer) => {
                    const chunk = data.toString();
                    serverStderr += chunk;
                    process.stderr.write(chunk);
                });
            }

            serverProcess.on("error", (error) => {
                console.error(`[Desktop App] Server process error: ${error}`);
                if (isSmokeTest) {
                    SmokeTestProtocol.error("runtime", `Server process error: ${error.message}`);
                } else {
                    dialog.showErrorBox("Server Error", `Failed to start scenario server: ${error.message}`);
                }
            });

            serverProcess.on("exit", (code, signal) => {
                console.log(`[Desktop App] Server process exited with code ${code} and signal ${signal}`);
                // In smoke test mode, emit error on unexpected exit
                if (isSmokeTest && code !== 0 && code !== null) {
                    const errorMsg = serverStderr.trim()
                        ? `Server crashed (exit ${code}): ${serverStderr.slice(0, 200)}`
                        : `Server crashed with exit code ${code}`;
                    SmokeTestProtocol.error("runtime", errorMsg);
                }
            });
        }
    } catch (error) {
        console.error(`[Desktop App] Failed to start server: ${error}`);
        dialog.showErrorBox("Startup Error", `Failed to start scenario server: ${error}`);
    }
}

function setupAutoUpdater() {
    // Skip if auto-updater is disabled, not packaged, or no provider configured
    if (!APP_CONFIG.ENABLE_AUTO_UPDATER || !app.isPackaged) {
        console.log("[Desktop App] Auto-updater disabled (not packaged or feature disabled)");
        return;
    }

    if (UPDATE_CONFIG.PROVIDER === "none") {
        console.log("[Desktop App] Auto-updater disabled (no update provider configured)");
        return;
    }

    // Configure the updater
    autoUpdater.logger = console;
    autoUpdater.autoDownload = true;
    autoUpdater.autoInstallOnAppQuit = true;

    // Set the update channel - electron-updater uses this for GitHub prereleases
    // and generic server channel directories
    autoUpdater.channel = UPDATE_CONFIG.CHANNEL;

    // For beta/dev channels on GitHub, allow prereleases
    if (UPDATE_CONFIG.PROVIDER === "github") {
        autoUpdater.allowPrerelease = UPDATE_CONFIG.CHANNEL !== "stable";
    }

    console.log(`[Desktop App] Auto-updater configured:`);
    console.log(`  Provider: ${UPDATE_CONFIG.PROVIDER}`);
    console.log(`  Channel: ${UPDATE_CONFIG.CHANNEL}`);
    console.log(`  Server: ${UPDATE_CONFIG.SERVER_URL || "(configured in app-update.yml)"}`);

    // Event handlers
    autoUpdater.on("checking-for-update", () => {
        console.log("[Desktop App] Checking for update...");
        recordTelemetry("update_check_started", { channel: UPDATE_CONFIG.CHANNEL });
    });

    autoUpdater.on("update-available", (info) => {
        console.log("[Desktop App] Update available:", info.version);
        recordTelemetry("update_available", {
            version: info.version,
            channel: UPDATE_CONFIG.CHANNEL,
            releaseDate: info.releaseDate,
        });

        // Show notification to user
        if (mainWindow && !mainWindow.isDestroyed()) {
            dialog.showMessageBox(mainWindow, {
                type: "info",
                title: "Update Available",
                message: `A new version (${info.version}) is available and will be downloaded automatically.`,
                buttons: ["OK"],
            });
        }
    });

    autoUpdater.on("update-not-available", (info) => {
        console.log("[Desktop App] Already on latest version:", info.version);
    });

    autoUpdater.on("error", (err) => {
        console.error("[Desktop App] Update error:", err.message);
        recordTelemetry("update_error", {
            error: err.message,
            channel: UPDATE_CONFIG.CHANNEL
        });
    });

    autoUpdater.on("download-progress", (progressObj) => {
        const percent = Math.round(progressObj.percent);
        const speed = (progressObj.bytesPerSecond / 1024 / 1024).toFixed(2);
        console.log(`[Desktop App] Download progress: ${percent}% (${speed} MB/s)`);
    });

    autoUpdater.on("update-downloaded", (info) => {
        console.log("[Desktop App] Update downloaded:", info.version);
        recordTelemetry("update_downloaded", {
            version: info.version,
            channel: UPDATE_CONFIG.CHANNEL
        });

        // Prompt user to restart
        if (mainWindow && !mainWindow.isDestroyed()) {
            dialog.showMessageBox(mainWindow, {
                type: "info",
                title: "Update Ready",
                message: `Version ${info.version} has been downloaded. The application will restart to apply the update.`,
                buttons: ["Restart Now", "Later"],
                defaultId: 0,
            }).then(({ response }) => {
                if (response === 0) {
                    autoUpdater.quitAndInstall(false, true);
                }
            });
        } else {
            // No window available, just install on quit
            console.log("[Desktop App] Update will be installed on next restart");
        }
    });

    // Check for updates based on configuration
    if (UPDATE_CONFIG.AUTO_CHECK) {
        // Delay initial check slightly to let the app fully initialize
        setTimeout(() => {
            console.log("[Desktop App] Performing automatic update check...");
            autoUpdater.checkForUpdatesAndNotify().catch((err) => {
                console.error("[Desktop App] Failed to check for updates:", err.message);
            });
        }, 3000);
    } else {
        console.log("[Desktop App] Automatic update check disabled - use menu to check manually");
    }
}

// Manual update check (can be triggered from menu)
async function checkForUpdatesManually(): Promise<void> {
    if (UPDATE_CONFIG.PROVIDER === "none") {
        if (mainWindow && !mainWindow.isDestroyed()) {
            dialog.showMessageBox(mainWindow, {
                type: "info",
                title: "Updates Disabled",
                message: "Auto-updates are not configured for this application.",
                buttons: ["OK"],
            });
        }
        return;
    }

    try {
        console.log("[Desktop App] Manual update check triggered");
        const result = await autoUpdater.checkForUpdates();
        if (!result?.updateInfo) {
            if (mainWindow && !mainWindow.isDestroyed()) {
                dialog.showMessageBox(mainWindow, {
                    type: "info",
                    title: "No Updates",
                    message: "You are running the latest version.",
                    buttons: ["OK"],
                });
            }
        }
    } catch (err) {
        console.error("[Desktop App] Manual update check failed:", err);
        if (mainWindow && !mainWindow.isDestroyed()) {
            dialog.showMessageBox(mainWindow, {
                type: "error",
                title: "Update Check Failed",
                message: `Could not check for updates: ${err instanceof Error ? err.message : String(err)}`,
                buttons: ["OK"],
            });
        }
    }
}

