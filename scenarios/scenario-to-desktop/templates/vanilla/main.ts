async function ensureRuntimeSecretsIfNeeded(): Promise<void> {
    if (!RUNTIME_CONTROL.ENABLED || !runtimeControlClient) return;
    try {
        const fetchSecrets = async (): Promise<RuntimeSecret[]> => {
            const status = await runtimeControlClient!.request<RuntimeSecretsResponse>("/secrets");
            return (status as RuntimeSecretsResponse)?.secrets || [];
        };
        const current = await fetchSecrets();
        const missing = current.filter(sec => sec.class === "user_prompt" && sec.required && !sec.has_value);
        if (missing.length === 0) return;
        const collected: Record<string, string> = {};
        for (const secret of missing) {
            const value = await promptForSecretValue(secret);
            if (value?.trim()) collected[secret.id] = value.trim();
        }
        if (Object.keys(collected).length === 0) throw new Error("Required secrets were not provided.");
        await runtimeControlClient.request("/secrets", { method: "POST", body: { secrets: collected } });
        const refreshed = await fetchSecrets();
        const stillMissing = refreshed.filter(sec => sec.class === "user_prompt" && sec.required && !sec.has_value);
        if (stillMissing.length > 0) throw new Error(`Secrets still missing: ${stillMissing.map(s => s.id).join(", ")}`);
    } catch (error) {
        console.error("[Desktop App] Failed to sync runtime secrets:", error);
        dialog.showErrorBox("Secrets required", String(error));
        throw error;
    }
}

