async function collectRuntimeDiagnostics(): Promise<RuntimeDiagnostics> {
    if (!runtimeControlClient) throw new Error("Runtime control client not initialized");
    const [ready, ports, telemetry] = await Promise.all([
        runtimeControlClient.request<RuntimeReadyResponse>("/readyz"),
        runtimeControlClient.request<RuntimePortsResponse>("/ports"),
        runtimeControlClient.request<RuntimeTelemetryResponse>("/telemetry"),
    ]);
    const logs: Record<string, string> = {};
    const services = new Set<string>();
    Object.keys((ready as RuntimeReadyResponse)?.details || {}).forEach(svc => services.add(svc));
    Object.keys((ports as RuntimePortsResponse)?.services || {}).forEach(svc => services.add(svc));
    for (const serviceId of services) {
        try {
            const logData = await runtimeControlClient.request<string>(
                `/logs/tail?serviceId=${encodeURIComponent(serviceId)}&lines=${RUNTIME_CONTROL.LOG_LINES}`,
                { expectText: true }
            );
            if (typeof logData === "string") logs[serviceId] = logData;
        } catch (error) {
            logs[serviceId] = `Failed to load logs: ${error}`;
        }
    }
    const diagnostics: RuntimeDiagnostics = { ready: ready as RuntimeReadyResponse, ports: ports as RuntimePortsResponse, logs };
    if ((ready as RuntimeReadyResponse)?.gpu) diagnostics.gpu = (ready as RuntimeReadyResponse).gpu;
    const tel = telemetry as RuntimeTelemetryResponse;
    if (tel?.path) diagnostics.telemetryPath = tel.path;
    if (tel?.upload_url) diagnostics.telemetryUploadUrl = tel.upload_url;
    return diagnostics;
}

async function showRuntimeDiagnostics(): Promise<void> {
    if (!RUNTIME_CONTROL.ENABLED) {
        await dialog.showMessageBox({ type: "info", title: "Runtime diagnostics unavailable", message: "Runtime control is disabled for this build." });
        return;
    }
    try {
        const diagnostics = await collectRuntimeDiagnostics();
        const messageLines = [`Ready: ${diagnostics.ready.ready ? "yes" : "no"}`, `Services: ${Object.keys(diagnostics.ports.services || diagnostics.ready.details || {}).length}`];
        const detailLines: string[] = [];
        // Build detail lines (GPU, readiness, ports, logs)
        const gpuInfo = diagnostics.gpu || diagnostics.ready.gpu;
        if (gpuInfo) {
            detailLines.push(`GPU: ${gpuInfo.available ? "available" : "not available"}${gpuInfo.method ? ` via ${gpuInfo.method}` : ""}${gpuInfo.reason ? ` (${gpuInfo.reason})` : ""}`);
        }
        for (const [svc, info] of Object.entries(diagnostics.ready.details || {})) {
            detailLines.push(`- ${svc}: ${info.ready ? "ready" : "not ready"}${info.message || info.reason ? ` (${info.message || info.reason})` : ""}`);
        }
        if (diagnostics.ports.services) {
            detailLines.push("Ports:");
            for (const [svc, svcPorts] of Object.entries(diagnostics.ports.services)) {
                detailLines.push(`- ${svc}: ${Object.entries(svcPorts as Record<string, number>).map(([n, v]) => `${n}=${v}`).join(", ")}`);
            }
        }
        const buttons: string[] = ["Close"];
        const uploadURL = RUNTIME_CONTROL.TELEMETRY_UPLOAD_URL || diagnostics.telemetryUploadUrl || "";
        if (diagnostics.telemetryPath) buttons.unshift("Copy telemetry path");
        if (uploadURL && diagnostics.telemetryPath) buttons.unshift("Upload telemetry");
        const result = await dialog.showMessageBox({
            type: diagnostics.ready.ready ? "info" : "warning",
            title: "Bundled runtime diagnostics",
            message: messageLines.join("\n"),
            detail: detailLines.join("\n"),
            buttons,
            defaultId: buttons.length - 1,
        });
        const picked = buttons[result.response];
        if (picked === "Copy telemetry path" && diagnostics.telemetryPath) {
            clipboard.writeText(diagnostics.telemetryPath);
            void recordTelemetry("runtime_diag_copy_path", { path: diagnostics.telemetryPath });
        } else if (picked === "Upload telemetry" && diagnostics.telemetryPath && uploadURL && telemetryUploader) {
            try {
                await telemetryUploader.upload(diagnostics.telemetryPath, uploadURL, "manual");
                await dialog.showMessageBox({ type: "info", title: "Telemetry uploaded", message: "Runtime telemetry uploaded successfully." });
            } catch (error) {
                await dialog.showMessageBox({ type: "error", title: "Telemetry upload failed", message: String(error) });
            }
        }
    } catch (error) {
        await dialog.showMessageBox({ type: "error", title: "Runtime diagnostics", message: `Failed to query runtime: ${error}` });
    }
}

