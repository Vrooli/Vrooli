function runtimePlatformKey(): string {
    const arch = process.arch === "x64" ? "x64" : process.arch;
    const os = process.platform === "darwin" ? "mac" : process.platform === "win32" ? "win" : "linux";
    return `${os}-${arch}`;
}

async function isPortFree(host: string, port: number): Promise<boolean> {
    return new Promise(resolve => {
        const server = nodeNet.createServer();
        server.once("error", () => resolve(false));
        server.once("listening", () => { server.close(() => resolve(true)); });
        server.listen(port, host);
    });
}

async function allocateIpcPort(host: string, preferred: number): Promise<{ port: number; changed: boolean }> {
    return new Promise((resolve, reject) => {
        const server = nodeNet.createServer();
        server.once("error", reject);
        server.listen(0, host, () => {
            const address = server.address();
            const port = typeof address === "object" && address ? address.port : 0;
            server.close(() => resolve({ port, changed: port !== preferred }));
        });
    });
}

async function resolveBundleRoot(): Promise<{ found: boolean; path: string | null; candidatesChecked: string[] }> {
    const bundleRoot = BUNDLED_RUNTIME.ROOT || "bundle";
    const candidates = [path.join(process.resourcesPath, bundleRoot), path.join(app.getAppPath(), bundleRoot)];
    for (const candidate of candidates) {
        if (await pathExists(candidate)) {
            console.log(`[Desktop App] Bundle found at: ${candidate}`);
            return { found: true, path: candidate, candidatesChecked: candidates };
        }
    }
    console.error(`[Desktop App] Bundle not found. Checked: ${candidates.join(", ")}`);
    return { found: false, path: null, candidatesChecked: candidates };
}

async function waitForFile(filePath: string, timeoutMs = 15000): Promise<void> {
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
        if (await pathExists(filePath)) return;
        await delay(150);
    }
    if (isSmokeTest) SmokeTestProtocol.error("runtime", `Timed out waiting for file: ${filePath}`);
    throw new Error(`file not found within timeout: ${filePath}`);
}

function formatValidationErrors(result: BundleValidationResult): string {
    const lines: string[] = [];
    if (result.missingBinaries.length > 0) { lines.push("Missing binaries:"); for (const mb of result.missingBinaries) lines.push(`  - ${mb.serviceId}: ${mb.path} (${mb.platform})`); }
    if (result.missingAssets.length > 0) { lines.push("Missing assets:"); for (const ma of result.missingAssets) lines.push(`  - ${ma.serviceId}: ${ma.path}`); }
    if (result.errors.length > 0 && lines.length === 0) { lines.push("Validation errors:"); for (const err of result.errors) lines.push(`  - ${err}`); }
    return lines.join("\n");
}

async function startBundledRuntime(): Promise<string> {
    if (isSmokeTest) SmokeTestProtocol.stage.bundleResolving();
    updateSplashStatus("validating-bundle", "Resolving bundle...");
    const bundleResolution = await resolveBundleRoot();
    if (!bundleResolution.found || !bundleResolution.path) throw new Error(`Bundled payload missing. Checked: [${bundleResolution.candidatesChecked.join(", ")}].`);
    const bundleRoot = bundleResolution.path;
    const manifestPath = path.join(bundleRoot, "bundle.json");
    if (!(await pathExists(manifestPath))) throw new Error(`Bundled manifest missing at ${manifestPath}`);

    updateSplashStatus("validating-bundle", "Reading bundle manifest...", 10);
    let manifestContent: any;
    try { manifestContent = JSON.parse(await fs.promises.readFile(manifestPath, "utf-8")); } catch (err) { throw new Error(`Failed to read bundle manifest: ${err}`); }

    updateSplashStatus("allocating-ports", "Allocating network ports...", 15);
    const ipcHost = manifestContent?.ipc?.host || "127.0.0.1";
    const preferredPort = Number(manifestContent?.ipc?.port) || 39200;
    const { port: runtimePort, changed } = await allocateIpcPort(ipcHost, preferredPort);
    if (changed) console.log(`[Desktop App] IPC port ${preferredPort} was busy; using ${runtimePort} instead`);
    manifestContent.ipc = manifestContent.ipc || {};
    manifestContent.ipc.port = runtimePort;
    RUNTIME_CONTROL.PORT = runtimePort;

    const appData = path.join(app.getPath("userData"), "runtime");
    await fs.promises.mkdir(appData, { recursive: true });
    runtimeAppDataRoot = appData;
    const stagedManifestPath = path.join(appData, "bundle.json");
    await fs.promises.writeFile(stagedManifestPath, JSON.stringify(manifestContent, null, 2), "utf-8");
    const portPath = path.join(appData, "runtime", "ipc_port");
    await fs.promises.mkdir(path.dirname(portPath), { recursive: true });
    await fs.promises.writeFile(portPath, `${runtimePort}`, "utf-8");

    // Pre-flight validation
    // DOC: docs/internal/SEAMS.md#bundle-module
    // Factory functions create testable wrappers around Node.js modules
    console.log("[Desktop App] Performing pre-flight bundle validation...");
    const bundleFs = createNodeBundleFileSystem(fs.promises);  // Requires fs.promises, not fs
    const bundlePathUtils = createNodeBundlePathUtils(path);
    const platformInfo = createRealPlatformInfo();             // No arguments - reads process internally
    const validationResult = await validateBundlePreFlight(bundleRoot, stagedManifestPath, bundleFs, bundlePathUtils, platformInfo);
    if (!validationResult.valid) {
        const errorDetails = formatValidationErrors(validationResult);
        await recordTelemetry("bundle_validation_failed", { errors: validationResult.errors, missingBinaries: validationResult.missingBinaries, missingAssets: validationResult.missingAssets });
        throw new Error(`Bundle validation failed:\n${errorDetails}`);
    }
    console.log("[Desktop App] Pre-flight bundle validation passed");

    const runtimePath = path.join(bundleRoot, "runtime", runtimePlatformKey(), process.platform === "win32" ? "runtime.exe" : "runtime");
    if (!(await pathExists(runtimePath))) throw new Error(`Bundled runtime binary not found for this platform (${runtimePath})`);
    const tokenRel = BUNDLED_RUNTIME.TOKEN_REL || "runtime/auth-token";
    const tokenPath = path.join(appData, tokenRel);
    RUNTIME_CONTROL.TOKEN_PATH_ENV = tokenPath;

    const args = ["--manifest", stagedManifestPath, "--bundle-root", bundleRoot, "--app-data", appData, "--dry-run=false"];
    const runtimeEnv: Record<string, string | undefined> = {
        ...process.env,
        VROOLI_API_SKIP_STALE_CHECK: "true",
        VROOLI_LIFECYCLE_MANAGED: "true",
        VROOLI_DESKTOP_MODE: "true",
        // Backward-compatible root used by existing scenarios.
        VROOLI_DATA: appData,
        // Canonical root for api-core/storage class directories.
        VROOLI_STORAGE_ROOT: path.join(appData, "storage"),
    };
    for (const [portKey, portConfig] of Object.entries(PORTS)) {
        if (portConfig.envVar && portConfig.port) { runtimeEnv[portConfig.envVar] = String(portConfig.port); console.log(`[Desktop App] Setting ${portConfig.envVar}=${portConfig.port}`); }
    }

    // Initialize exit tracker
    exitTracker = createExitTracker();
    exitTracker.reset();

    if (isSmokeTest) SmokeTestProtocol.stage.runtimeStarting();
    updateSplashStatus("starting-runtime", "Starting runtime services...", 30);

    runtimeProcess = spawn(runtimePath, args, { stdio: ["inherit", "inherit", "pipe"], env: runtimeEnv });
    await launchTrace.emit("runtime_spawned", "bundled-runtime", "bundled_runtime");
    let stderrErrorEmitted = false;
    if (runtimeProcess.stderr) {
        runtimeProcess.stderr.on("data", (data: Buffer) => {
            const chunk = data.toString();
            exitTracker!.appendStderr(chunk);
            process.stderr.write(chunk);
            if (isSmokeTest && !stderrErrorEmitted) {
                const match = matchErrorPattern(chunk, DEFAULT_ERROR_PATTERNS);
                if (match) { SmokeTestProtocol.error(match.kind as any, match.message); stderrErrorEmitted = true; }
            }
        });
    }
    runtimeProcess.on("exit", (code, signal) => {
        exitTracker!.recordExit(code, signal);
        void recordTelemetry("bundled_runtime_exit", { code, signal });
        if (isSmokeTest && code !== 0 && code !== null) {
            const exitInfo = exitTracker!.info;
            const errorMsg = exitInfo.stderr.trim() ? `Runtime crashed (exit ${code}): ${exitInfo.stderr.slice(0, 200)}` : `Runtime crashed with exit code ${code}`;
            SmokeTestProtocol.error("runtime", errorMsg);
        }
    });

    if (isSmokeTest) SmokeTestProtocol.stage.waitingForToken();
    updateSplashStatus("waiting-for-token", "Waiting for authentication token...", 40);
    console.log(`[Desktop App] Waiting for runtime auth token at: ${tokenPath}`);
    await waitForFile(tokenPath, APP_CONFIG.SERVER_CHECK_TIMEOUT_MS);
    await launchTrace.emit("runtime_token_available", "bundled-runtime", "bundled_runtime", { available: "true" });

    await initializeRuntimeControlClient();

    if (isSmokeTest) SmokeTestProtocol.stage.runtimeHealthz();
    updateSplashStatus("checking-health", "Checking service health...", 50);
    await runtimeControlClient!.waitForHealth(APP_CONFIG.SERVER_CHECK_TIMEOUT_MS);
    await launchTrace.emit("runtime_health_ready", "bundled-runtime", "bundled_runtime");

    await ensureRuntimeSecretsIfNeeded();

    await applyStartupDelay("RUNTIME_READY");

    if (isSmokeTest) SmokeTestProtocol.stage.runtimeReadyz();
    updateSplashStatus("checking-ready", "Verifying services are ready...", 60);
    const readyDeadline = Date.now() + APP_CONFIG.SERVER_CHECK_TIMEOUT_MS;
    let runtimeReady = false;
    while (Date.now() < readyDeadline) {
        try {
            const ready = await runtimeControlClient!.request<RuntimeReadyResponse>("/readyz");
            if ((ready as RuntimeReadyResponse)?.ready) {
                runtimeReady = true;
                break;
            }
        } catch { /* runtime may still be starting */ }
        await delay(350);
    }
    if (!runtimeReady) {
        const error = `Bundled runtime did not become ready within ${APP_CONFIG.SERVER_CHECK_TIMEOUT_MS}ms`;
        await launchTrace.emit("runtime_ready", "bundled-runtime", "bundled_runtime", { available: "false" }, "error");
        throw new Error(error);
    }
    await launchTrace.emit("runtime_ready", "bundled-runtime", "bundled_runtime");

    if (isSmokeTest) SmokeTestProtocol.stage.runtimePorts();
    updateSplashStatus("discovering-ports", "Discovering service endpoints...", 70);
    const ports = await runtimeControlClient!.request<RuntimePortsResponse>("/ports");
    const serviceId = BUNDLED_RUNTIME.UI_SERVICE || Object.keys((ports as RuntimePortsResponse).services || {})[0];
    const portName = BUNDLED_RUNTIME.UI_PORT_NAME || "http";
    const svcPorts = (ports as RuntimePortsResponse).services?.[serviceId!];
    const port = svcPorts?.[portName];
    if (!serviceId || !port) throw new Error("Bundled runtime started but did not expose a UI port");
    await launchTrace.emit("port_discovered", "bundled-runtime", "bundled_runtime", { service: serviceId, port_name: portName });

    updateSplashStatus("loading-ui", "Starting user interface...", 80);
    const url = `http://127.0.0.1:${port}/`;
    await recordTelemetry("bundled_runtime_ready", { bundleRoot, serviceId, portName, port });
    return url;
}

async function shutdownRuntime(): Promise<void> {
    const child = runtimeProcess;
    runtimeProcess = null;
    if (RUNTIME_CONTROL.ENABLED && runtimeControlClient) {
        try { await runtimeControlClient.request("/shutdown", { method: "POST" }); } catch (error) { console.warn("[Desktop App] Failed to request runtime shutdown", error); }
    }
    if (!child || child.exitCode !== null) return;
    const waitForExit = async (timeoutMs: number): Promise<boolean> => await new Promise(resolve => {
        const timer = setTimeout(() => { child.removeListener("exit", onExit); resolve(false); }, timeoutMs);
        const onExit = () => { clearTimeout(timer); resolve(true); };
        child.once("exit", onExit);
    });
    if (await waitForExit(5000)) return;
    try { child.kill("SIGTERM"); } catch { /* process already exited */ }
    if (await waitForExit(2000)) return;
    try { child.kill("SIGKILL"); } catch { /* process already exited */ }
    await waitForExit(1000);
}

