// ===== SMOKE TEST RUNNER =====

async function runSmokeTest(): Promise<void> {
    SmokeTestProtocol.init();
    // Initialize telemetry for smoke test
    const userData = app.getPath("userData");
    const telemetryPath = path.join(userData, "deployment-telemetry.jsonl");
    telemetryRecorder = createTelemetryRecorder(createTelemetryFileSystem(fs.promises), { filePath: telemetryPath, sessionId, sessionKind, deploymentMode: APP_CONFIG.DEPLOYMENT_MODE, serverType: APP_CONFIG.SERVER_TYPE });
    await telemetryRecorder.initialize();
    await startLaunchProfiler();
    await recordTelemetry("smoke_test_started", { deploymentMode: APP_CONFIG.DEPLOYMENT_MODE, serverType: APP_CONFIG.SERVER_TYPE });
    let success = false, failureMessage = "", runtimeUrl = "";
    try {
        if (isBundledMode) {
            const bundleResolution = await resolveBundleRoot();
            if (!bundleResolution.found || !bundleResolution.path) { const errorMsg = `Bundled payload missing. Checked: [${bundleResolution.candidatesChecked.join(", ")}].`; SmokeTestProtocol.error("config", errorMsg); throw new Error(errorMsg); }
            const bundleRoot = bundleResolution.path;
            const manifestPath = path.join(bundleRoot, "bundle.json");
            if (!(await pathExists(manifestPath))) { SmokeTestProtocol.error("config", `Manifest missing at ${manifestPath}`); throw new Error(`Manifest missing at ${manifestPath}`); }
            const bundleFs = createNodeBundleFileSystem(fs.promises), bundlePathUtils = createNodeBundlePathUtils(path), platformInfo = createRealPlatformInfo();
            const validationResult = await validateBundlePreFlight(bundleRoot, manifestPath, bundleFs, bundlePathUtils, platformInfo);
            if (!validationResult.valid) { const errorDetails = formatValidationErrors(validationResult); SmokeTestProtocol.error("validation", `Bundle validation failed: ${errorDetails}`); throw new Error(`Bundle validation failed: ${errorDetails}`); }
            if (!BUNDLED_RUNTIME.SUPPORTED) { SmokeTestProtocol.error("config", "Bundled runtime not supported"); throw new Error("Bundled runtime not supported"); }
            runtimeUrl = await startBundledRuntime();
            SmokeTestProtocol.stage.uiServerCheck();
            await checkServerReady(runtimeUrl, smokeTestTimeoutMs);
            // Stability check
            console.log(`[Smoke Test] Server ready, performing ${POST_SUCCESS_STABILITY_DELAY_MS}ms stability check...`);
            const stabilityStartTime = Date.now();
            while (Date.now() - stabilityStartTime < POST_SUCCESS_STABILITY_DELAY_MS) {
                if (exitTracker?.hasExitedUnexpectedly()) { const exitInfo = exitTracker.info; const errorMsg = exitInfo.stderr.trim() ? `Runtime crashed during stability check (exit ${exitInfo.code}): ${exitInfo.stderr.slice(0, 200)}` : `Runtime crashed during stability check with exit code ${exitInfo.code}`; SmokeTestProtocol.error("runtime", errorMsg); throw new Error(errorMsg); }
                await delay(STABILITY_CHECK_INTERVAL_MS);
            }
            console.log("[Smoke Test] Stability check passed");
        } else if (APP_CONFIG.SERVER_TYPE === "static") {
            const staticPath = path.resolve(app.getAppPath(), APP_CONFIG.SERVER_PATH);
            if (!(await pathExists(staticPath))) { SmokeTestProtocol.error("config", `Static UI missing at ${staticPath}`); throw new Error(`Static UI missing at ${staticPath}`); }
        } else {
            runtimeUrl = desktopValidationTargetURL;
            SmokeTestProtocol.stage.uiServerCheck();
            await checkServerReady(desktopValidationTargetURL, smokeTestTimeoutMs);
        }
        if (isBundledMode && exitTracker?.hasExitedUnexpectedly()) { const exitInfo = exitTracker.info; const errorMsg = exitInfo.stderr.trim() ? `Runtime crashed before completion (exit ${exitInfo.code}): ${exitInfo.stderr.slice(0, 200)}` : `Runtime crashed before completion with exit code ${exitInfo.code}`; SmokeTestProtocol.error("runtime", errorMsg); throw new Error(errorMsg); }
        SmokeTestProtocol.ready();
        success = true;
    } catch (error) {
        failureMessage = String(error);
        if (failureMessage.includes("not ready") || failureMessage.includes("timeout") || failureMessage.includes("ECONNREFUSED")) SmokeTestProtocol.error("network", failureMessage);
        else if (!failureMessage.includes("SMOKE_TEST_ERROR")) SmokeTestProtocol.error("runtime", failureMessage);
    } finally { if (isBundledMode) await shutdownRuntime(); }
    await stopLaunchProfiler();
    if (success) await recordTelemetry("smoke_test_passed", { serverUrl: runtimeUrl || SERVER_URL }); else await recordTelemetry("smoke_test_failed", { error: failureMessage }, "error");
    SmokeTestProtocol.result(success, failureMessage);
    if (smokeTestUploadURL && telemetryRecorder) {
        try {
            telemetryUploader = createTelemetryUploader(createTelemetryFileSystem(fs.promises), createFetchHttpClient(), createTelemetryPathUtils(path), { scenarioName: LOCAL_VROOLI_BOOTSTRAP.SCENARIO_NAME || APP_CONFIG.APP_NAME, deploymentMode: APP_CONFIG.DEPLOYMENT_MODE, statePath: path.join(getRuntimeAppDataRoot(), "telemetry-upload.json") });
            await telemetryUploader.upload(telemetryRecorder.getFilePath()!, smokeTestUploadURL, "smoke-test");
            SmokeTestProtocol.upload(true);
        } catch (error) { SmokeTestProtocol.upload(false, String(error)); }
    }
    await launchTrace.emit("protocol_completed", "electron", "main", { result: success ? "passed" : "failed" }, success ? "info" : "error");
    await launchTrace.complete();
    SmokeTestProtocol.exit();
    // A smoke run has no user-facing windows and must not remain alive because
    // Electron retains an internal handle after app.exit(). The runtime has
    // already been shut down in the finally block, so force the one-shot
    // validation process to terminate after its final evidence marker.
    process.exit(success ? 0 : 1);
}

