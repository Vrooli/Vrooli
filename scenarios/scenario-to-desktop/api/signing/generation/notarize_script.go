// generateNotarizeJS generates the afterSign notarization script for electron-builder.
func generateNotarizeJS(config *types.MacOSSigningConfig) ([]byte, error) {
	if config == nil || !config.Notarize {
		return nil, nil
	}

	var tmplStr string
	var data map[string]string

	// Choose template based on credential method
	if config.AppleAPIKeyID != "" && config.AppleAPIKeyFile != "" && config.AppleAPIIssuerID != "" {
		// API Key method (preferred)
		tmplStr = notarizeScriptTemplateAPIKey

		apiKeyIDEnv := types.DefaultAppleAPIKeyIDEnv     // #nosec G101 -- environment variable name, never a credential value
		apiKeyFileEnv := types.DefaultAppleAPIKeyFileEnv // #nosec G101 -- environment variable name, never a credential value
		apiIssuerEnv := types.DefaultAppleAPIIssuerIDEnv

		data = map[string]string{
			"APIKeyID":      config.AppleAPIKeyID,
			"APIKeyIDEnv":   apiKeyIDEnv,
			"APIKeyFile":    config.AppleAPIKeyFile,
			"APIKeyFileEnv": apiKeyFileEnv,
			"APIIssuer":     config.AppleAPIIssuerID,
			"APIIssuerEnv":  apiIssuerEnv,
			"TeamID":        config.TeamID,
		}
	} else {
		// App-Specific Password method
		tmplStr = notarizeScriptTemplateAppPassword

		appleIDEnv := config.AppleIDEnv
		if appleIDEnv == "" {
			appleIDEnv = types.DefaultAppleIDEnv
		}

		appleIDPasswordEnv := config.AppleIDPasswordEnv
		if appleIDPasswordEnv == "" {
			appleIDPasswordEnv = types.DefaultAppleIDPasswordEnv // gitleaks:allow -- environment-variable name, never a credential value
		}

		data = map[string]string{
			"AppleIDEnv":         appleIDEnv,
			"AppleIDPasswordEnv": appleIDPasswordEnv,
			"TeamID":             config.TeamID,
		}
	}

	tmpl, err := template.New("notarize").Parse(tmplStr)
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}

// NotarizeCredentialMethod returns which credential method is configured.
// Returns "api_key", "app_password", or "" if notarization is not configured.
func NotarizeCredentialMethod(config *types.MacOSSigningConfig) string {
	if config == nil || !config.Notarize {
		return ""
	}

	if config.AppleAPIKeyID != "" && config.AppleAPIKeyFile != "" && config.AppleAPIIssuerID != "" {
		return "api_key"
	}

	if config.AppleIDEnv != "" || config.AppleIDPasswordEnv != "" {
		return "app_password"
	}

	return ""
}
