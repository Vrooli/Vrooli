package main

import (
	"context"
	"fmt"
	"net/http"
)

// recommendationResponse is the shared default for the browser and terminal
// surfaces. It is derived from manifests, so a new deployment does not need a
// second hard-coded starter list in onboarding.
type recommendationResponse struct {
	Profile     string   `json:"profile"`
	Scenarios   []string `json:"scenarios"`
	Resources   []string `json:"resources"`
	Explanation string   `json:"explanation"`
}

func buildRecommendation(ctx context.Context) (recommendationResponse, error) {
	// Keep the compatibility endpoint, but make it a projection of the same
	// bounded profile evaluator used by the guided browser flow. The endpoint
	// no longer owns a second manifest-derived starter list.
	evaluation, err := onboardingProfilesService().Evaluate(ctx, "general-purpose", map[string]any{
		"purposes": []any{"use-local-apps", "develop-apps"},
	}, map[string]any{"target": "local"})
	if err != nil {
		return recommendationResponse{}, err
	}
	if !evaluation.Valid {
		return recommendationResponse{}, fmt.Errorf("default profile evaluation is invalid: %v", evaluation.Issues)
	}
	return recommendationResponse{
		Profile:     evaluation.Profile.ID,
		Scenarios:   evaluation.Scenarios,
		Resources:   evaluation.Resources,
		Explanation: "This compatibility recommendation is generated by the general-purpose profile and its selected local-use and development purposes.",
	}, nil
}

func (s *Server) handleV2Recommendation(w http.ResponseWriter, r *http.Request) {
	recommendation, err := buildRecommendation(r.Context())
	if err != nil {
		if writeCatalogDegraded(w, err) {
			return
		}
		writeJSON(w, http.StatusInternalServerError, map[string]string{"error": err.Error()})
		return
	}
	writeJSON(w, http.StatusOK, recommendation)
}
