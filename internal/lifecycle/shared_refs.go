// ProtoArtifactStampPath is the repo-relative identity stamp of the Proto
// artifact installed as the compatibility view under packages/proto/gen.
const ProtoArtifactStampPath = "packages/proto/gen/.vrooli-proto-artifact.json"

// SharedSourceRoot is one repo-relative path (directory or file) a scenario
// build reads outside the scenario directory, with the reference requiring it.
type SharedSourceRoot struct {
	Path   string
	Reason string
}

// SharedSourceRoots lists the repository sources a scenario's declared
// component builds reach outside the scenario directory. It is the single
// resolver the baseline freeze copies into an engagement:
//
//   - go_module components: the `go list -deps` closure of every build entry.
//     A package of a separately versioned module freezes the module's first
//     two directory levels below its root (packages/proto/gen/go), and a
//     package of the repository module its top two levels (internal/tuning).
//     Every module's go.mod and go.sum in the closure is frozen, the
//     repository's included: a scenario that replaces the whole repository
//     module (../../..) compiles against its go.mod.
//   - builders that follow workspace file dependencies (pnpm_vite,
//     node_bundle): each `file:` dependency, transitively, plus the governed
//     `requires` closure. A governed dependency must already hold the outputs
//     its lifecycle builds (dist/), because a frozen root is never rebuilt.
//   - bundler and compiler configuration (vite.config.*, vitest*.config.*,
//     tsconfig*.json) of those builders: literal relative paths that leave
//     the scenario (aliases, tsconfig paths and extends).
//
// When Proto's generated outputs are frozen, the artifact identity stamp is
// frozen with them. Roots nested in another root are dropped. An unresolvable
// reference is an error: a freeze that silently misses a root would let the
// serving build read the moving working tree.
func SharedSourceRoots(ctx context.Context, repoRoot string, item scenario.Scenario) ([]SharedSourceRoot, error) {
	repo, err := filepath.Abs(filepath.Clean(repoRoot))
	if err != nil {
		return nil, err
	}
	scenarioDir, err := filepath.Abs(filepath.Clean(item.SourcePath()))
	if err != nil {
		return nil, err
	}
	collector := sharedRootCollector{repo: repo, scenarioDir: scenarioDir, roots: map[string]string{}}
	for _, name := range orderedComponentNames(item.Manifest.Components) {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		component := item.Manifest.Components[name]
		spec, ok := builderRegistry[strings.TrimSpace(component.Build.Kind)]
		if !ok || spec.Reserved {
			continue
		}
		buildDir, err := componentWorkingDir(scenarioDir, component.Build.Dir)
		if err != nil {
			return nil, fmt.Errorf("component %s: %w", name, err)
		}
		if spec.ClosureResolver == closureResolverGoList {
			if err := collector.addGoClosure(ctx, name, buildDir, goBuildEntries(component)); err != nil {
				return nil, err
			}
		}
		if spec.FollowsWorkspaceFileDeps {
			if err := collector.addFileDependencies(name, filepath.Join(buildDir, "package.json"), map[string]struct{}{}); err != nil {
				return nil, err
			}
			if err := collector.addConfigReferences(name, buildDir); err != nil {
				return nil, err
			}
		}
	}
	for root := range collector.roots {
		if root == path.Dir(ProtoArtifactStampPath) || strings.HasPrefix(root, path.Dir(ProtoArtifactStampPath)+"/") {
			if _, err := os.Stat(filepath.Join(repo, filepath.FromSlash(ProtoArtifactStampPath))); err == nil {
				collector.add(ProtoArtifactStampPath, "proto:artifact identity")
			}
			break
		}
	}
	return collector.compact(), nil
}

// CaptureExcludePatterns returns gitignore-syntax patterns, anchored at the
// scenario directory, for the scenario's declared build outputs and runtime
// data directories. A restore point is a code undo; these are regenerated by
// the next build or owned by the running instance.
func CaptureExcludePatterns(item scenario.Scenario) []string {
	scenarioDir := item.SourcePath()
	var patterns []string
	add := func(abs string, dir bool) {
		rel, err := filepath.Rel(scenarioDir, abs)
		if err != nil || rel == "." || strings.HasPrefix(rel, "..") {
			return
		}
		pattern := "/" + filepath.ToSlash(rel)
		if dir {
			pattern += "/"
		}
		patterns = append(patterns, pattern)
	}
	for _, name := range orderedComponentNames(item.Manifest.Components) {
		component := item.Manifest.Components[name]
		spec, ok := builderRegistry[strings.TrimSpace(component.Build.Kind)]
		if ok && !spec.Reserved {
			if targets, err := componentBuildTargets(name, scenarioDir, item.Slug, component, spec, runtimeGOOS()); err == nil {
				for _, target := range targets {
					if spec.StageDirectory {
						add(filepath.Dir(target.Output), true)
					} else {
						add(target.Output, false)
					}
				}
			}
		}
		for _, relative := range append(append([]string(nil), component.Run.DataDirs...), component.Run.LogDir) {
			if strings.TrimSpace(relative) == "" {
				continue
			}
			if dir, err := componentWorkingDir(scenarioDir, relative); err == nil {
				add(dir, true)
			}
		}
	}
	sort.Strings(patterns)
	return patterns
}

// ScenarioAt loads the scenario descriptor whose manifest lives in dir (a
// working tree or a capture source).
func ScenarioAt(name, dir string) (scenario.Scenario, error) {
	servicePath := filepath.Join(dir, repocontractmeta.ProjectConfigDir, "service.json")
	manifest, err := scenario.ReadService(servicePath)
	if err != nil {
		return scenario.Scenario{}, err
	}
	return scenario.Scenario{Slug: name, Path: dir, ServicePath: servicePath, Manifest: manifest}, nil
}

type sharedRootCollector struct {
	repo        string
	scenarioDir string
	roots       map[string]string
}

// add records a repo-relative root unless it lies inside the scenario (which
// the restore point already holds).
func (c *sharedRootCollector) add(rel, reason string) {
	rel = path.Clean(filepath.ToSlash(rel))
	if rel == "." || rel == "" || strings.HasPrefix(rel, "../") || rel == ".." {
		return
	}
	abs := filepath.Join(c.repo, filepath.FromSlash(rel))
	if pathUnderRoot(c.scenarioDir, abs) || pathUnderRoot(abs, c.scenarioDir) {
		return
	}
	if _, exists := c.roots[rel]; !exists {
		c.roots[rel] = reason
	}
}

// repoRel maps an absolute path into the repository; ok is false outside it.
func (c *sharedRootCollector) repoRel(abs string) (string, bool) {
	clean := repoCanonicalPath(c.repo, filepath.Clean(abs))
	if !pathUnderRoot(c.repo, clean) {
		return "", false
	}
	return relUnder(c.repo, clean), true
}

func goBuildEntries(component scenario.Component) []string {
	entries := []string{strings.TrimSpace(component.Build.Entry)}
	for _, extra := range component.Build.Outputs {
		entries = append(entries, strings.TrimSpace(extra.Entry))
	}
	seen := map[string]struct{}{}
	out := make([]string, 0, len(entries))
	for _, entry := range entries {
		if entry == "" {
			entry = "."
		}
		if _, ok := seen[entry]; ok {
			continue
		}
		seen[entry] = struct{}{}
		out = append(out, entry)
	}
	return out
}

// goListDeps runs `go list -deps -json` for build entries. It is a variable
// so tests can substitute the toolchain.
var goListDeps = func(ctx context.Context, dir string, entries []string) ([]byte, error) {
	goBin, err := exec.LookPath("go")
	if err != nil {
		return nil, err
	}
	ctx, cancel := context.WithTimeout(ctx, tuning.LifecycleOperationTimeout())
	defer cancel()
	// VCS stamping is irrelevant to a dependency listing and fails outside a
	// checkout (or under a stray ancestor .git).
	args := append([]string{"list", "-buildvcs=false", "-deps", "-json"}, entries...)
	cmd := shell.NewCommandContext(ctx, goBin, args...)
	cmd.Dir = dir
	cmd.Env = envkit.WithOverlay(envkit.Env(os.Environ()), envkit.SameScenario, envkit.Env{"GOWORK=off"})
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("%w: %s", err, strings.TrimSpace(lastLines(stderr.String(), 6)))
	}
	return out, nil
}

func (c *sharedRootCollector) addGoClosure(ctx context.Context, component, buildDir string, entries []string) error {
	if _, err := os.Stat(filepath.Join(buildDir, "go.mod")); err != nil {
		return fmt.Errorf("component %s: go module %s: %w", component, buildDir, err)
	}
	raw, err := goListDeps(ctx, buildDir, entries)
	if err != nil {
		return fmt.Errorf("component %s: go list -deps in %s: %w", component, buildDir, err)
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	for dec.More() {
		var pkg goListPackage
		if err := dec.Decode(&pkg); err != nil {
			return fmt.Errorf("component %s: parse go list output: %w", component, err)
		}
		if pkg.Standard || strings.TrimSpace(pkg.Dir) == "" {
			continue
		}
		dirRel, ok := c.repoRel(pkg.Dir)
		if !ok {
			continue // module cache
		}
		moduleRel := ""
		if pkg.Module != nil && strings.TrimSpace(pkg.Module.Dir) != "" {
			if rel, ok := c.repoRel(pkg.Module.Dir); ok {
				moduleRel = rel
			}
		}
		within := strings.TrimPrefix(strings.TrimPrefix(dirRel, moduleRel), "/")
		if moduleRel == "." || moduleRel == "" {
			moduleRel, within = "", dirRel
		}
		root := path.Join(moduleRel, firstSegments(within, 2))
		c.add(root, "go:"+component)
		if pkg.Module != nil && strings.TrimSpace(pkg.Module.GoMod) != "" {
			if goMod, ok := c.repoRel(pkg.Module.GoMod); ok {
				c.add(goMod, "go:module "+path.Dir(goMod))
				if _, err := os.Stat(filepath.Join(c.repo, filepath.FromSlash(path.Join(path.Dir(goMod), "go.sum")))); err == nil {
					c.add(path.Join(path.Dir(goMod), "go.sum"), "go:module "+path.Dir(goMod))
				}
			}
		}
	}
	return nil
}

func firstSegments(rel string, n int) string {
	if rel == "" || rel == "." {
		return ""
	}
	parts := strings.Split(rel, "/")
	if len(parts) > n {
		parts = parts[:n]
	}
	return strings.Join(parts, "/")
}

// addFileDependencies adds each file: dependency of packageJSON, its own
// file: dependencies, and the governed requires closure.
func (c *sharedRootCollector) addFileDependencies(component, packageJSON string, seen map[string]struct{}) error {
	specs, err := fileDependenciesWithDeps(packageJSON, defaultHostProbeDeps())
	if err != nil {
		return fmt.Errorf("component %s: read %s: %w", component, packageJSON, err)
	}
	for _, spec := range specs {
		target := resolveCheckPath(filepath.Dir(packageJSON), strings.TrimPrefix(spec.Spec, "file:"))
		if err := c.addPackageRoot(component, target, "file:"+spec.Name, seen); err != nil {
			return err
		}
	}
	return nil
}

func (c *sharedRootCollector) addPackageRoot(component, target, reason string, seen map[string]struct{}) error {
	if pathUnderRoot(c.scenarioDir, target) {
		return nil
	}
	rel, ok := c.repoRel(target)
	if !ok {
		return fmt.Errorf("component %s: %s resolves outside the repository (%s)", component, reason, target)
	}
	if _, done := seen[rel]; done {
		return nil
	}
	seen[rel] = struct{}{}
	info, err := os.Stat(target)
	if err != nil {
		return fmt.Errorf("component %s: %s: %w", component, reason, err)
	}
	c.add(rel, reason)
	if !info.IsDir() {
		return nil
	}
	pkg, pkgRoot, governed, err := loadGovernedPackage(c.repo, target)
	if err != nil {
		return fmt.Errorf("component %s: %s: %w", component, reason, err)
	}
	if governed && filepath.Clean(pkgRoot) == filepath.Clean(target) {
		if err := requireBuiltOutputs(pkg, target); err != nil {
			return fmt.Errorf("component %s: %s: %w", component, reason, err)
		}
		for _, required := range pkg.Manifest.Package.Lifecycle.Requires {
			requiredRoot := filepath.Join(c.repo, "packages", strings.TrimSpace(required))
			if err := c.addPackageRoot(component, requiredRoot, "requires:"+required, seen); err != nil {
				return err
			}
		}
	}
	if _, err := os.Stat(filepath.Join(target, "package.json")); err == nil {
		return c.addFileDependencies(component, filepath.Join(target, "package.json"), seen)
	}
	return nil
}

// requireBuiltOutputs fails when a governed package lacks the outputs its
// lifecycle build declares. Installed dependencies (node_modules) are not
// frozen and are skipped.
func requireBuiltOutputs(pkg packagegov.Package, root string) error {
	for _, command := range append(append([]packagegov.CommandSpec{}, pkg.Manifest.Package.Lifecycle.Generate...), pkg.Manifest.Package.Lifecycle.Build...) {
		for _, output := range command.Outputs {
			prefix := strings.TrimSpace(output)
			if index := strings.IndexAny(prefix, "*?["); index >= 0 {
				prefix = prefix[:index]
			}
			prefix = strings.TrimSuffix(prefix, "/")
			if prefix == "" || prefix == "node_modules" || strings.HasPrefix(prefix, "node_modules/") {
				continue
			}
			if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(prefix))); err != nil {
				return fmt.Errorf("declared output %s of %q is missing; build the package before capturing (vrooli scenario setup)", output, command.Name)
			}
		}
	}
	return nil
}

var configRelativePathRE = regexp.MustCompile(`["'](\.\.?/[^"'\s]*)["']`)

// addConfigReferences scans bundler and compiler configuration for literal
// relative paths that leave the scenario: Vite/Vitest aliases, tsconfig paths
// and extends. It only adds roots; a literal that does not exist is ignored.
func (c *sharedRootCollector) addConfigReferences(component, buildDir string) error {
	entries, err := os.ReadDir(buildDir)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return err
	}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !isBuildConfigFile(name) {
			continue
		}
		data, err := os.ReadFile(filepath.Join(buildDir, name))
		if err != nil {
			return fmt.Errorf("component %s: read %s: %w", component, name, err)
		}
		configRel, _ := filepath.Rel(c.scenarioDir, filepath.Join(buildDir, name))
		for _, match := range configRelativePathRE.FindAllStringSubmatch(string(data), -1) {
			literal := stripGlobSuffix(match[1])
			if literal == "" {
				continue
			}
			target := filepath.Join(buildDir, filepath.FromSlash(literal))
			if pathUnderRoot(c.scenarioDir, target) {
				continue
			}
			if _, err := os.Stat(target); err != nil {
				continue
			}
			rel, ok := c.repoRel(target)
			if !ok || rel == "." {
				continue
			}
			c.add(rel, "alias:"+filepath.ToSlash(configRel))
		}
	}
	return nil
}

func isBuildConfigFile(name string) bool {
	switch {
	case strings.HasPrefix(name, "vite.config."), strings.HasPrefix(name, "vitest") && strings.Contains(name, ".config."):
		return true
	case strings.HasPrefix(name, "tsconfig") && strings.HasSuffix(name, ".json"):
		return true
	}
	return false
}

// stripGlobSuffix removes a trailing wildcard path (tsconfig "paths" use
// dir/*) so the directory itself is frozen.
func stripGlobSuffix(literal string) string {
	parts := strings.Split(literal, "/")
	for len(parts) > 0 && strings.ContainsAny(parts[len(parts)-1], "*?") {
		parts = parts[:len(parts)-1]
	}
	return strings.Join(parts, "/")
}

// compact returns sorted roots, dropping any root nested inside another.
func (c *sharedRootCollector) compact() []SharedSourceRoot {
	paths := make([]string, 0, len(c.roots))
	for rel := range c.roots {
		paths = append(paths, rel)
	}
	sort.Strings(paths)
	out := make([]SharedSourceRoot, 0, len(paths))
	for _, rel := range paths {
		nested := false
		for _, kept := range out {
			if strings.HasPrefix(rel, kept.Path+"/") {
				nested = true
				break
			}
		}
		if !nested {
			out = append(out, SharedSourceRoot{Path: rel, Reason: c.roots[rel]})
		}
	}
	return out
}

func lastLines(text string, n int) string {
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, "\n")
}
