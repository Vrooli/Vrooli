const TransitionTableGeneratedCheck = "transitionTable"

func Render(c contract.Contract, built artifact.Artifact) (string, error) {
	switch filepath.Ext(c.Outputs.DeclarationsPath) {
	case ".go":
		return renderGo(c, built)
	case ".ts":
		return renderTypeScript(c, built)
	default:
		return "", fmt.Errorf("unsupported declarationsPath extension for %s: %s", c.FlowID, c.Outputs.DeclarationsPath)
	}
}

func renderGo(c contract.Contract, built artifact.Artifact) (string, error) {
	if c.Runtime.Go == nil {
		return "", fmt.Errorf("runtime.go is required for %s", c.FlowID)
	}
	rt := c.Runtime.Go
	var b strings.Builder
	b.WriteString("// Code generated by tools/temporal-model from ")
	b.WriteString(c.ContractPath)
	b.WriteString("; DO NOT EDIT.\n\n")
	b.WriteString("package ")
	b.WriteString(rt.Package)
	b.WriteString("\n\n")
	b.WriteString("import \"fmt\"\n\n")
	b.WriteString("const (\n")
	for _, state := range c.States {
		fmt.Fprintf(&b, "\t%s%s %s = %q\n", rt.ConstantPrefix, pascal(state.ID), rt.StatusType, state.ID)
	}
	b.WriteString(")\n\n")
	b.WriteString("const (\n")
	for _, event := range c.Events {
		fmt.Fprintf(&b, "\t%s%s %s = %q\n", rt.ConstantPrefix, pascal(event.ID), rt.EventType, event.ID)
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "const %sContractPath = %q\n", rt.ConstantPrefix, built.Source.ContractPath)
	fmt.Fprintf(&b, "const %sModelPath = %q\n", rt.ConstantPrefix, built.Source.ModelPath)
	fmt.Fprintf(&b, "const %sGeneratorPath = %q\n", rt.ConstantPrefix, built.Source.GeneratorPath)
	fmt.Fprintf(&b, "const %sContractSHA256 = %q\n", rt.ConstantPrefix, built.Source.ContractSHA256)
	fmt.Fprintf(&b, "const %sModelSHA256 = %q\n", rt.ConstantPrefix, built.Source.ModelSHA256)
	fmt.Fprintf(&b, "const %sGeneratorSHA256 = %q\n\n", rt.ConstantPrefix, built.Source.GeneratorSHA256)
	fmt.Fprintf(&b, "var %sFormalInvariants = []string{%s}\n", lowerFirst(rt.ConstantPrefix), quotedList(built.Invariants))
	fmt.Fprintf(&b, "var %sFormalGeneratedChecks = []string{%s}\n\n", lowerFirst(rt.ConstantPrefix), quotedList(built.GeneratedChecks))
	fmt.Fprintf(&b, "func All%sStatuses() []%s {\n", rt.ConstantPrefix, rt.StatusType)
	fmt.Fprintf(&b, "\treturn []%s{%s}\n", rt.StatusType, goStatusList(c, rt))
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func All%sEvents() []%s {\n", rt.ConstantPrefix, rt.EventType)
	fmt.Fprintf(&b, "\treturn []%s{%s}\n", rt.EventType, goEventList(c, rt))
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func %sIsValidEvent(status %s, event %s) bool {\n", rt.ConstantPrefix, rt.StatusType, rt.EventType)
	b.WriteString("\tswitch status {\n")
	for _, state := range c.States {
		fmt.Fprintf(&b, "\tcase %s%s:\n", rt.ConstantPrefix, pascal(state.ID))
		b.WriteString("\t\tswitch event {\n")
		for _, transition := range transitionsFrom(c, state.ID) {
			if !transition.WantError {
				fmt.Fprintf(&b, "\t\tcase %s%s:\n", rt.ConstantPrefix, pascal(transition.Event))
				b.WriteString("\t\t\treturn true\n")
			}
		}
		b.WriteString("\t\t}\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("\treturn false\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func %sNextStatus(status %s, event %s) %s {\n", rt.ConstantPrefix, rt.StatusType, rt.EventType, rt.StatusType)
	b.WriteString("\tswitch status {\n")
	for _, state := range c.States {
		fmt.Fprintf(&b, "\tcase %s%s:\n", rt.ConstantPrefix, pascal(state.ID))
		b.WriteString("\t\tswitch event {\n")
		for _, transition := range transitionsFrom(c, state.ID) {
			fmt.Fprintf(&b, "\t\tcase %s%s:\n", rt.ConstantPrefix, pascal(transition.Event))
			fmt.Fprintf(&b, "\t\t\treturn %s%s\n", rt.ConstantPrefix, pascal(transition.To))
		}
		b.WriteString("\t\t}\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("\treturn status\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func Transition%sStatus(status %s, event %s) (%s, error) {\n", rt.ConstantPrefix, rt.StatusType, rt.EventType, rt.StatusType)
	fmt.Fprintf(&b, "\tnext := %sNextStatus(status, event)\n", rt.ConstantPrefix)
	fmt.Fprintf(&b, "\tif !%sIsValidEvent(status, event) {\n", rt.ConstantPrefix)
	b.WriteString("\t\treturn next, fmt.Errorf(\"cannot apply %s from %s\", event, status)\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn next, nil\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func %sFormalExpectedInvariants() []string {\n", rt.ConstantPrefix)
	fmt.Fprintf(&b, "\treturn append([]string(nil), %sFormalInvariants...)\n", lowerFirst(rt.ConstantPrefix))
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func %sFormalExpectedGeneratedChecks() []string {\n", rt.ConstantPrefix)
	fmt.Fprintf(&b, "\treturn append([]string(nil), %sFormalGeneratedChecks...)\n", lowerFirst(rt.ConstantPrefix))
	b.WriteString("}\n")
	formatted, err := goformat.Source([]byte(b.String()))
	if err != nil {
		return "", err
	}
	return string(formatted), nil
}

func renderTypeScript(c contract.Contract, built artifact.Artifact) (string, error) {
	if c.Runtime.TypeScript == nil {
		return "", fmt.Errorf("runtime.typescript is required for %s", c.FlowID)
	}
	rt := c.Runtime.TypeScript
	var b strings.Builder
	b.WriteString("// Code generated by tools/temporal-model from ")
	b.WriteString(c.ContractPath)
	b.WriteString("; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "export const %s = [\n", rt.StatusesConst)
	for _, state := range c.States {
		fmt.Fprintf(&b, "  %q,\n", state.ID)
	}
	b.WriteString("] as const;\n\n")
	fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n\n", rt.StatusType, rt.StatusesConst)
	fmt.Fprintf(&b, "export const %s = [\n", rt.EventsConst)
	for _, event := range c.Events {
		fmt.Fprintf(&b, "  %q,\n", event.ID)
	}
	b.WriteString("] as const;\n\n")
	fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n\n", rt.EventType, rt.EventsConst)
	if rt.StateUnionType != "" {
		renderTypeScriptRuntimeUnion(&b, rt.StateUnionType, "status", c.States, rt.StateVariants, rt.PayloadTypes)
	}
	if rt.EventUnionType != "" {
		renderTypeScriptRuntimeUnion(&b, rt.EventUnionType, "type", c.Events, rt.EventVariants, rt.PayloadTypes)
	}
	renderTypeScriptFixtureContract(&b, c, rt)
	tableConst := lowerFirst(strings.TrimSuffix(rt.StatusType, "Status")) + "TransitionTable"
	helperBase := strings.TrimSuffix(rt.StatusType, "Status")
	if helperBase == "" {
		helperBase = rt.StatusType
	}
	fmt.Fprintf(&b, "type %sTransitionRow = {\n", helperBase)
	fmt.Fprintf(&b, "  readonly to: %s;\n", rt.StatusType)
	b.WriteString("  readonly wantError: boolean;\n")
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "const %s = {\n", tableConst)
	for _, state := range c.States {
		fmt.Fprintf(&b, "  %q: {\n", state.ID)
		for _, transition := range transitionsFrom(c, state.ID) {
			fmt.Fprintf(&b, "    %q: { to: %q, wantError: %t },\n", transition.Event, transition.To, transition.WantError)
		}
		b.WriteString("  },\n")
	}
	fmt.Fprintf(&b, "} satisfies Record<%s, Record<%s, %sTransitionRow>>;\n\n", rt.StatusType, rt.EventType, helperBase)
	fmt.Fprintf(&b, "export const is%sEventValid = (status: %s, event: %s): boolean =>\n", helperBase, rt.StatusType, rt.EventType)
	fmt.Fprintf(&b, "  !%s[status][event].wantError;\n\n", tableConst)
	fmt.Fprintf(&b, "export const next%sStatus = (status: %s, event: %s): %s =>\n", helperBase, rt.StatusType, rt.EventType, rt.StatusType)
	fmt.Fprintf(&b, "  %s[status][event].to;\n\n", tableConst)
	fmt.Fprintf(&b, "export const transition%sStatus = (status: %s, event: %s): %s => {\n", helperBase, rt.StatusType, rt.EventType, rt.StatusType)
	fmt.Fprintf(&b, "  const row = %s[status][event];\n", tableConst)
	b.WriteString("  if (row.wantError) {\n")
	b.WriteString("    throw new Error(`cannot apply ${event} from ${status}`);\n")
	b.WriteString("  }\n")
	b.WriteString("  return row.to;\n")
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "export const %s = {\n", rt.FormalExpectationConst)
	fmt.Fprintf(&b, "  contractPath: %q,\n", built.Source.ContractPath)
	fmt.Fprintf(&b, "  contractSha256: %q,\n", built.Source.ContractSHA256)
	fmt.Fprintf(&b, "  modelPath: %q,\n", built.Source.ModelPath)
	fmt.Fprintf(&b, "  modelSha256: %q,\n", built.Source.ModelSHA256)
	fmt.Fprintf(&b, "  generatorPath: %q,\n", built.Source.GeneratorPath)
	fmt.Fprintf(&b, "  generatorSha256: %q,\n", built.Source.GeneratorSHA256)
	fmt.Fprintf(&b, "  invariants: [%s],\n", tsQuotedList(built.Invariants))
	fmt.Fprintf(&b, "  generatedChecks: [%s],\n", tsQuotedList(built.GeneratedChecks))
	b.WriteString("} as const;\n")
	return b.String(), nil
}

func renderTypeScriptRuntimeUnion[T interface {
	contract.State | contract.Event
}](b *strings.Builder, typeName string, discriminator string, items []T, variants map[string]map[string]string, payloadTypes map[string]string) {
	if len(variants) == 0 {
		return
	}
	fmt.Fprintf(b, "export type %s =\n", typeName)
	for i, item := range items {
		id := itemID(item)
		prefix := "  | "
		if i == 0 {
			prefix = "  "
		}
		fmt.Fprintf(b, "%s{ readonly %s: %q", prefix, discriminator, id)
		fields := sortedKeys(variants[id])
		for _, field := range fields {
			alias := variants[id][field]
			fmt.Fprintf(b, "; readonly %s: %s", field, payloadTypes[alias])
		}
		b.WriteString(" }")
		if i == len(items)-1 {
			b.WriteString(";\n\n")
		} else {
			b.WriteString("\n")
		}
	}
}

func itemID(item any) string {
	switch value := item.(type) {
	case contract.State:
		return value.ID
	case contract.Event:
		return value.ID
	default:
		return ""
	}
}

func renderTypeScriptFixtureContract(b *strings.Builder, c contract.Contract, rt *contract.TypeScriptRuntime) {
	stateFixtureType := strings.TrimSuffix(rt.StatusType, "Status") + "StateFixtureMap"
	if rt.StateUnionType != "" {
		stateFixtureType = rt.StateUnionType + "FixtureMap"
		fmt.Fprintf(b, "export type %s<RuntimeState = %s> = Record<%s, () => RuntimeState>;\n", stateFixtureType, rt.StateUnionType, rt.StatusType)
	} else {
		fmt.Fprintf(b, "export type %s<RuntimeState> = Record<%s, () => RuntimeState>;\n", stateFixtureType, rt.StatusType)
	}
	eventFixtureType := strings.TrimSuffix(rt.EventType, "EventType") + "EventFixtureMap"
	if eventFixtureType == rt.EventType+"EventFixtureMap" {
		eventFixtureType = strings.TrimSuffix(rt.EventType, "Event") + "EventFixtureMap"
	}
	if rt.EventUnionType != "" {
		fmt.Fprintf(b, "export type %s<RuntimeEvent = %s> = Record<%s, () => RuntimeEvent>;\n\n", eventFixtureType, rt.EventUnionType, rt.EventType)
	} else {
		fmt.Fprintf(b, "export type %s<RuntimeEvent> = Record<%s, () => RuntimeEvent>;\n\n", eventFixtureType, rt.EventType)
	}
	base := strings.TrimSuffix(rt.StatusType, "Status")
	if base == "" {
		base = rt.StatusType
	}
	fmt.Fprintf(b, "export const %sReplayFixtureContract = {\n", lowerFirst(base))
	fmt.Fprintf(b, "  states: %s,\n", rt.StatusesConst)
	fmt.Fprintf(b, "  events: %s,\n", rt.EventsConst)
	fmt.Fprintf(b, "} as const satisfies { readonly states: readonly %s[]; readonly events: readonly %s[] };\n\n", rt.StatusType, rt.EventType)
	_ = c
}

func transitionsFrom(c contract.Contract, from string) []contract.ExpandedTransition {
	out := make([]contract.ExpandedTransition, 0, len(c.Events))
	for _, event := range c.Events {
		for _, transition := range c.ExpandedTransitions {
			if transition.From == from && transition.Event == event.ID {
				out = append(out, transition)
				break
			}
		}
	}
	return out
}

func goStatusList(c contract.Contract, rt *contract.GoRuntime) string {
	values := make([]string, 0, len(c.States))
	for _, state := range c.States {
		values = append(values, rt.ConstantPrefix+pascal(state.ID))
	}
	return strings.Join(values, ", ")
}

func goEventList(c contract.Contract, rt *contract.GoRuntime) string {
	values := make([]string, 0, len(c.Events))
	for _, event := range c.Events {
		values = append(values, rt.ConstantPrefix+pascal(event.ID))
	}
	return strings.Join(values, ", ")
}

func quotedList(values []string) string {
	if len(values) == 0 {
		return ""
	}
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return strings.Join(quoted, ", ")
}

func tsQuotedList(values []string) string {
	return strings.Join(strings.Split(quotedList(values), ", "), ", ")
}

func sortedKeys(values map[string]string) []string {
	out := make([]string, 0, len(values))
	for key := range values {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}

var wordBoundary = regexp.MustCompile(`[^A-Za-z0-9]+`)

func pascal(value string) string {
	parts := wordBoundary.Split(value, -1)
	var out strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		lower := strings.ToLower(part)
		out.WriteString(strings.ToUpper(lower[:1]))
		if len(lower) > 1 {
			out.WriteString(lower[1:])
		}
	}
	return out.String()
}

func lowerFirst(value string) string {
	if value == "" {
		return value
	}
	return strings.ToLower(value[:1]) + value[1:]
}
