/**
 * Source of the shared app-notification service worker, served by the
 * scenario web server at /vrooli-notify/sw.js (see app-notifications.ts).
 *
 * Its scope is /vrooli-notify/, so it never controls a page and never sees a
 * fetch: it sits beside the scenario's own sw.js without touching it. It only
 * shows pushes and opens taps. Declarative Web Push (iOS 18.4+) is shown by
 * the browser itself; this worker covers every other browser with the same
 * payload, and the classic {title, body, url} shape as well.
 *
 * iOS ignores the URL passed to openWindow/navigate when the installed app is
 * already running in the background, so a tap also stashes the target and
 * posts it to open windows; initAppNotifications() in the page reads both.
 */
export const APP_NOTIFICATIONS_WORKER_SOURCE = String.raw`// Vrooli shared app-notification worker. Generated by @vrooli/api-base; do not edit.
const STASH_CACHE = "vrooli-notify";
const STASH_KEY = "/vrooli-notify/pending-navigation";

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

function readPayload(event) {
  if (!event.data) return {};
  try {
    return event.data.json();
  } catch {
    return { body: event.data.text() };
  }
}

self.addEventListener("push", (event) => {
  const data = readPayload(event);
  const declarative = data && data.web_push === 8030 && data.notification;
  const n = declarative ? data.notification : data;
  const url = new URL((declarative ? n.navigate : data.url) || "/", self.location.origin).href;
  // Every push must show a notification: iOS revokes a subscription after
  // pushes that show nothing.
  event.waitUntil(self.registration.showNotification(n.title || "Notification", {
    body: n.body || "",
    tag: n.tag || data.id || undefined,
    icon: data.icon || undefined,
    data: { url },
  }));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || new URL("/", self.location.origin).href;
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(STASH_CACHE);
      await cache.put(STASH_KEY, new Response(JSON.stringify({ url, at: Date.now() }), { headers: { "Content-Type": "application/json" } }));
    } catch {
      // The stash is a backup for iOS; the message and openWindow still run.
    }
    const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    for (const client of windows) client.postMessage({ type: "vrooli-notify:navigate", url });
    if (windows.length > 0) {
      try { await windows[0].focus(); } catch { /* focus can be refused */ }
      return;
    }
    await self.clients.openWindow(url);
  })());
});
`
